async function runTool(hooks, name, argv, place = PRE_CUT) {
  const prompt = PROMPTS.runner({
    argv: toolWords(name, argv),
    envelopeDir: place.dir,
    envelopeName: place.tag === undefined ? name : `${name}-${place.tag}`,
    ...(place.write === undefined ? {} : { write: place.write }),
  });
  const out = await hooks.agent(
    prompt,
    agentOptions(
      'runner',
      place.tag === undefined ? name : `${name}:${place.tag}`,
      TOOL_SCHEMAS[name],
    ),
  );
  return typeof out === 'object' && out !== null ? out : null;
}
function toolWords(name, argv) {
  return ['node', '--import', 'tsx', ...TOOL_COMMANDS[name], ...argv];
}
const PR_PLACEHOLDER = '<pr>';
function toolCommandLine(name, argv) {
  return toolWords(name, argv)
    .map((word) => (word === PR_PLACEHOLDER ? word : shellWord(word)))
    .join(' ');
}
function envelopeProblem(tool, out) {
  if (out === null) return `the runner returned nothing for ${tool}`;
  const reason = out.reason === undefined ? '' : ` (${out.reason})`;
  const detail = out.errors?.[0]?.message ?? out.stderrTail ?? 'no error named';
  return `${tool} ${out.status ?? 'without a status'}${reason}: ${detail}`;
}

async function cleanupSpent(hooks, live) {
  const report = {
    tornDown: [],
    retired: [],
    skipped: [],
    residue: [],
    blocked: null,
    stop: null,
  };
  if (live?.status !== 'ok' || live.runs === undefined) {
    report.blocked = envelopeProblem('live-runs', live);
    return report;
  }
  for (const run of live.runs) {
    await cleanupRun(hooks, run, report);
    if (report.stop !== null) break;
  }
  return report;
}
async function cleanupRun(hooks, run, report) {
  const target = spentTarget(run);
  if (target === null) return;
  if ('why' in target) report.skipped.push(target);
  else await tearDownSpent(hooks, { path: target.path, branch: run.branch }, report);
}
async function tearDownSpent(hooks, spent, report) {
  const { path, branch } = spent;
  const place = preCutPlace(`spent-${String(report.tornDown.length + report.residue.length + 1)}`);
  const out = await runTool(hooks, 'teardown', [path], place);
  if (out?.status === 'ok') {
    report.tornDown.push(path);
    const retired = await runTool(hooks, 'retire-run', ['.', '--branch', branch], place);
    if (retired?.status === 'ok') report.retired.push(branch);
    else report.residue.push(`${branch}: ${envelopeProblem('retire-run', retired)}`);
  } else if (out?.status === 'refused' && out.reason === 'source-shrank') {
    report.stop = envelopeProblem('teardown', out);
  } else {
    report.residue.push(`${path}: ${envelopeProblem('teardown', out)}`);
  }
}
function spentTarget(run) {
  if (run.spentUnverified) {
    return { path: run.path, why: 'its PR is over, but the PR head could not be checked' };
  }
  if (!run.spent) return null;
  if (run.dirty !== false) {
    return {
      path: run.path,
      why: run.dirty === true ? 'uncommitted changes' : 'dirtiness unknown',
    };
  }
  if (run.nested.length > 0) {
    return { path: run.path, why: `nested worktrees: ${run.nested.join(', ')}` };
  }
  return { path: run.path };
}

async function syncMasterStep(hooks, ctx) {
  const out = await runTool(hooks, 'sync-master', [ctx.batch], runPlace(ctx, ctx.tag));
  return { ...syncVerdict(out), conflicts: out?.conflicts ?? [], version: out?.version ?? null };
}
function syncVerdict(out) {
  if (out?.status === 'ok' && out.outcome === 'up-to-date') {
    return {
      verdict: 'up-to-date',
      commit: null,
      upstream: out.upstream ?? null,
      message: 'origin/master already merged',
    };
  }
  if (out?.status === 'ok' && out.outcome === 'merged' && typeof out.commit === 'string') {
    return {
      verdict: 'merged',
      commit: out.commit,
      upstream: out.upstream ?? null,
      message: `merged origin/master as ${out.commit}`,
    };
  }
  const message = envelopeProblem('sync-master', out);
  if (out?.status === 'refused' && out.reason === 'code-conflict') {
    return { verdict: 'code-conflict', commit: null, upstream: null, message };
  }
  return { verdict: 'failed', commit: null, upstream: null, message };
}

const RESYNC_MERGEABLE = 'MERGEABLE';
async function runResync(hooks, rawArgs) {
  const args = parseResyncArgs(rawArgs);
  const base = { pr: null, sync: null, pushed: false, mergeable: null, cleanup: noCleanup() };
  if (args.refusal !== undefined) {
    return { ...base, status: 'refused', branch: '', message: args.refusal };
  }
  const { branch } = args;
  hooks.phase(RESYNC_PHASE_TITLES.preflight);
  const live = await runTool(hooks, 'live-runs', ['.'], preCutPlace('resync'));
  if (typeof live?.worktree !== 'string') {
    const message =
      live === null ? envelopeProblem('live-runs', live) : 'live-runs named no main checkout';
    return { ...base, branch, status: 'stopped', message };
  }
  const bound = withCheckout(hooks, live.worktree);
  const cleanup = await cleanupSpent(bound, live);
  const report = { ...base, branch, cleanup };
  if (cleanup.stop !== null) return { ...report, status: 'stopped', message: cleanup.stop };
  const attached = await attachStep(bound, branch);
  if ('stop' in attached) return { ...report, status: 'stopped', message: attached.stop };
  const withPr = { ...report, pr: attached.pr };
  hooks.phase(RESYNC_PHASE_TITLES.merge);
  const sync = await syncMasterStep(bound, { ...attached, tag: 'resync' });
  if (sync.verdict === 'code-conflict' || sync.verdict === 'failed') {
    return {
      ...withPr,
      sync,
      status: 'stopped',
      message: `master sync ${sync.verdict}: ${sync.message}`,
    };
  }
  hooks.phase(RESYNC_PHASE_TITLES.push);
  return pushStep(bound, attached, { ...withPr, sync });
}
async function attachStep(hooks, branch) {
  const cut = await runTool(hooks, 'cut-batch', ['.', '--attach', branch], preCutPlace('resync'));
  const { batch, reportDir, attach } = cut ?? {};
  if (
    cut?.status !== 'ok' ||
    typeof batch !== 'string' ||
    typeof reportDir !== 'string' ||
    attach === undefined ||
    attach === null
  ) {
    return { stop: envelopeProblem('cut-batch', cut) };
  }
  if (attach.created) {
    const argv = [batch, '--report-dir', reportDir];
    const prov = await runTool(hooks, 'provision-batch', argv, runPlace({ reportDir }, 'resync'));
    if (prov?.status !== 'ok') return { stop: envelopeProblem('provision-batch', prov) };
  }
  return { batch, reportDir, pr: attach.pr };
}
async function pushStep(hooks, attached, report) {
  const argv = [attached.batch, '--push-only', '--log', `${attached.reportDir}/resync-push.log`];
  const out = await runTool(hooks, 'publish', argv, runPlace(attached, 'resync'));
  if (out?.status !== 'ok') {
    return { ...report, status: 'stopped', message: envelopeProblem('publish', out) };
  }
  const pushed = out.pushed === true;
  const mergeable = out.mergeable ?? null;
  const pr = out.pr?.number ?? report.pr;
  const state =
    mergeable === RESYNC_MERGEABLE ? 'confirmed' : `unconfirmed (${mergeable ?? 'unread'})`;
  const message = `${pushed ? 'pushed' : 'nothing to push'}; PR #${String(pr)} mergeable ${state}`;
  return { ...report, status: 'done', message, pr, pushed, mergeable };
}
function noCleanup() {
  return { tornDown: [], retired: [], skipped: [], residue: [], blocked: null, stop: null };
}

return await runResync({ agent, parallel, pipeline, phase, log }, args);
