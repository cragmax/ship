async function syncMasterStep(hooks, ctx) {
  const start = await runTool(hooks, 'sync-master', [ctx.batch], runPlace(ctx.reportDir, ctx.tag));
  const found = { conflicts: start?.conflicts ?? [], version: start?.version ?? null };
  if (start?.status === 'conflict' && start.outcome === 'needs-resolution') {
    return { ...(await resolveAndContinue(hooks, ctx, start.pending ?? [])), ...found };
  }
  return { ...syncVerdict(start, 'merged'), ...found };
}
async function resolveAndContinue(hooks, ctx, pending) {
  if (pending.length === 0) {
    return syncFailure(
      `sync-master needs resolution but named no path; merge left in ${ctx.batch}`,
    );
  }
  const values = { batch: ctx.batch, pending, reportPath: `${ctx.reportDir}/resolve.md` };
  const answer = await AGENT_CALLS.resolver(hooks, values, ctx.tag);
  if (answer?.verdict !== 'resolved') {
    const said = answer === null ? 'returned nothing' : `said ${answer.summary}`;
    return syncFailure(`the resolver ${said}; merge left in progress in ${ctx.batch}`);
  }
  const done = await runTool(
    hooks,
    'sync-master',
    [ctx.batch, '--continue'],
    runPlace(ctx.reportDir, `${ctx.tag}-continue`),
  );
  return syncVerdict(done, 'resolved');
}
function syncVerdict(out, merged) {
  if (out?.status === 'ok' && out.outcome === 'up-to-date') {
    return {
      verdict: 'up-to-date',
      commit: null,
      upstream: out.upstream ?? null,
      message: 'origin/master already merged',
    };
  }
  if (out?.status === 'ok' && out.outcome === 'merged' && typeof out.commit === 'string') {
    return {
      verdict: merged,
      commit: out.commit,
      upstream: out.upstream ?? null,
      message: `merged origin/master as ${out.commit}`,
    };
  }
  const message = envelopeProblem('sync-master', out);
  if (out?.status === 'refused' && out.reason === 'code-conflict') {
    return { verdict: 'code-conflict', commit: null, upstream: null, message };
  }
  return syncFailure(message);
}
function syncFailure(message) {
  return { verdict: 'failed', commit: null, upstream: null, message };
}

const RESYNC_MERGEABLE = 'MERGEABLE';
async function runResync(hooks, rawArgs) {
  const args = parseResyncArgs(rawArgs);
  const base = { pr: null, sync: null, pushed: false, mergeable: null, cleanup: noCleanup() };
  if (args.refusal !== undefined) {
    return { ...base, status: 'refused', branch: '', message: args.refusal };
  }
  const { branch } = args;
  hooks.phase(RESYNC_PHASE_TITLES.preflight);
  const live = await runTool(hooks, 'live-runs', ['.'], { ...PRE_CUT, tag: 'resync' });
  const cleanup = await cleanupSpent(hooks, live);
  const report = { ...base, branch, cleanup };
  if (cleanup.stop !== null) return { ...report, status: 'stopped', message: cleanup.stop };
  const attached = await attachStep(hooks, branch);
  if ('stop' in attached) return { ...report, status: 'stopped', message: attached.stop };
  const withPr = { ...report, pr: attached.pr };
  hooks.phase(RESYNC_PHASE_TITLES.merge);
  const sync = await syncMasterStep(hooks, { ...attached, tag: 'resync' });
  if (sync.verdict === 'code-conflict' || sync.verdict === 'failed') {
    return {
      ...withPr,
      sync,
      status: 'stopped',
      message: `master sync ${sync.verdict}: ${sync.message}`,
    };
  }
  hooks.phase(RESYNC_PHASE_TITLES.push);
  return pushStep(hooks, attached, { ...withPr, sync });
}
async function attachStep(hooks, branch) {
  const cut = await runTool(hooks, 'cut-batch', ['.', '--attach', branch], {
    ...PRE_CUT,
    tag: 'resync',
  });
  const { batch, reportDir, attach } = cut ?? {};
  if (
    cut?.status !== 'ok' ||
    typeof batch !== 'string' ||
    typeof reportDir !== 'string' ||
    attach === undefined ||
    attach === null
  ) {
    return { stop: envelopeProblem('cut-batch', cut) };
  }
  if (attach.created) {
    const argv = [batch, '--report-dir', reportDir];
    const prov = await runTool(hooks, 'provision-batch', argv, runPlace(reportDir, 'resync'));
    if (prov?.status !== 'ok') return { stop: envelopeProblem('provision-batch', prov) };
  }
  return { batch, reportDir, pr: attach.pr };
}
async function pushStep(hooks, attached, report) {
  const argv = [attached.batch, '--push-only', '--log', `${attached.reportDir}/resync-push.log`];
  const out = await runTool(hooks, 'publish', argv, runPlace(attached.reportDir, 'resync'));
  if (out?.status !== 'ok') {
    return { ...report, status: 'stopped', message: envelopeProblem('publish', out) };
  }
  const pushed = out.pushed === true;
  const mergeable = out.mergeable ?? null;
  const pr = out.pr?.number ?? report.pr;
  const state =
    mergeable === RESYNC_MERGEABLE ? 'confirmed' : `unconfirmed (${mergeable ?? 'unread'})`;
  const message = `${pushed ? 'pushed' : 'nothing to push'}; PR #${String(pr)} mergeable ${state}`;
  return { ...report, status: 'done', message, pr, pushed, mergeable };
}
function noCleanup() {
  return { tornDown: [], skipped: [], residue: [], blocked: null, stop: null };
}

return await runResync({ agent, parallel, pipeline, phase, log }, args);
