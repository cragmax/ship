function createCommitQueue() {
  let tail = Promise.resolve();
  return {
    enqueue: (task) => {
      const run = tail.then(() => task());
      tail = run.then(
        () => undefined,
        () => undefined,
      );
      return run;
    },
  };
}
function classifyLanding(land) {
  if (land?.status === 'ok' && typeof land.commit === 'string') return 'committed';
  if (land?.batchClean !== true) return 'halt';
  if (land.status === 'conflict') return 'conflict';
  if (land.status === 'refused' && land.reason === 'slice-not-single-commit') return 'blocked';
  const step = land.errors?.[0]?.step;
  const rolledBackStep = step === 'commit' || step === 'build';
  if (land.status === 'failed' && land.rolledBack === true && rolledBackStep) return 'blocked';
  return 'halt';
}
function landingEvent(land, at) {
  const reason = envelopeProblem('land', land);
  switch (classifyLanding(land)) {
    case 'committed':
      return { kind: 'committed', issue: at.issue };
    case 'conflict':
      return { kind: 'harvest-conflict', issue: at.issue };
    case 'blocked':
      return { kind: 'blocked', issue: at.issue, reason };
    case 'halt':
      return { kind: 'epic-halt', epic: at.epic, reason };
  }
}
function teardownEvent(teardown, epic) {
  if (teardown?.status !== 'refused' || teardown.reason !== 'source-shrank') return null;
  return { kind: 'epic-halt', epic, reason: envelopeProblem('teardown', teardown) };
}
function teardownResidue(teardown) {
  return teardown?.status === 'ok' ? null : envelopeProblem('teardown', teardown);
}
function settleEvents(primary, halt, at) {
  if (halt !== null) {
    const blocked = { kind: 'blocked', issue: at.issue, reason: halt.reason };
    return { events: at.entry === 'halted' ? [blocked] : [halt, blocked], entry: 'halted' };
  }
  if (at.entry === 'halted' && primary.kind === 'committed') {
    const blocked = {
      kind: 'blocked',
      issue: at.issue,
      reason: 'landed after its epic halted',
    };
    return { events: [blocked], entry: 'halted' };
  }
  return { events: [primary], entry: at.entry };
}

const LEASE_LINE =
  /^with-lease: waited (\d+(?:\.\d+)?)s for (\w+)@(\S+), held (\d+(?:\.\d+)?)s(?:, waited on (.+?))?\r?$/u;
function formatLeaseLine(timing) {
  const waited = timing.waitedSeconds.toFixed(1);
  const held = timing.heldSeconds.toFixed(1);
  const suffix = timing.waitedOn === undefined ? '' : `, waited on ${timing.waitedOn}`;
  return `with-lease: waited ${waited}s for ${timing.type}@${timing.endpoint}, held ${held}s${suffix}`;
}
const LEASE_WAIT_LINE = /^with-lease: waiting for \w+@\S+ /u;
const LEASE_UNKNOWN_HOLDER = 'an unknown holder';
function formatLeaseWaitLine(wait) {
  const { holder } = wait;
  const head = `with-lease: waiting for ${wait.type}@${wait.endpoint} — held by`;
  if (holder === null) return `${head} ${LEASE_UNKNOWN_HOLDER}`;
  const state = holder.alive ? 'alive' : 'dead, lock reclaimed once stale';
  return `${head} ${leaseHolderLabel(holder.cwd)} (pid ${String(holder.pid)}, since ${holder.since}, ${state}): ${holder.command}`;
}
function leaseWaitedOn(holder) {
  if (holder === null) return LEASE_UNKNOWN_HOLDER;
  return `${leaseHolderLabel(holder.cwd)} (pid ${String(holder.pid)})`;
}
function leaseHolderLabel(cwd) {
  return cwd
    .split(/[\\/]/u)
    .filter((segment) => segment !== '')
    .slice(-2)
    .join('/');
}
function parseLeaseLine(line) {
  const match = LEASE_LINE.exec(line);
  if (match === null) return null;
  const [, waited = '', type = '', endpoint = '', held = '', waitedOn] = match;
  const timing = { type, endpoint, waitedSeconds: Number(waited), heldSeconds: Number(held) };
  return waitedOn === undefined ? timing : { ...timing, waitedOn };
}
function parseLeaseLines(text) {
  const timings = [];
  for (const line of text.split('\n')) {
    const timing = parseLeaseLine(line);
    if (timing !== null) timings.push(timing);
  }
  return timings;
}
