const ARG_KEYS = ['epics', 'issues', 'exclude', 'preflightOnly', 'maxSlices'];
class ArgsError extends Error {}
function parseShipArgs(raw) {
  try {
    return { args: typeof raw === 'string' ? parseText(raw) : parseObject(raw) };
  } catch (err) {
    if (!(err instanceof ArgsError)) throw err;
    return {
      refusal: {
        kind: 'usage',
        message: `${err.message}; expected epics|issues N... [--exclude] [--preflight-only] [--max-slices K]`,
      },
    };
  }
}
function parseText(text) {
  const trimmed = text.trim();
  if (trimmed.startsWith('{')) return parseObject(parseJson(trimmed));
  const [first, ...rest] = trimmed.split(/\s+/);
  return validated({ selection: selectionWord(first), ...parseTokens(rest) });
}
function selectionWord(word) {
  if (word === 'epics' || word === 'issues') return word;
  throw new ArgsError(
    word === undefined || word === ''
      ? 'no arguments'
      : `'${word}' is not epics or issues (bare numbers are ambiguous)`,
  );
}
function parseTokens(tokens) {
  const numbers = [];
  const args = { numbers, exclude: false, preflightOnly: false, maxSlices: MAX_SLICES };
  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i] ?? '';
    switch (token) {
      case '--exclude':
        args.exclude = true;
        break;
      case '--preflight-only':
        args.preflightOnly = true;
        break;
      case '--max-slices':
        args.maxSlices = positiveInteger(tokens[++i], '--max-slices');
        break;
      default:
        numbers.push(...numberList(token));
    }
  }
  return args;
}
function parseObject(raw) {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) {
    throw new ArgsError(raw === undefined || raw === null ? 'no arguments' : 'not an object');
  }
  const record = raw;
  const unknownKey = Object.keys(record).find((key) => !ARG_KEYS.includes(key));
  if (unknownKey !== undefined) throw new ArgsError(`unknown key '${unknownKey}'`);
  const hasEpics = Object.hasOwn(record, 'epics');
  if (hasEpics === Object.hasOwn(record, 'issues')) {
    throw new ArgsError('give exactly one of epics and issues');
  }
  const selection = hasEpics ? 'epics' : 'issues';
  const list = record[selection];
  if (!Array.isArray(list)) throw new ArgsError(`${selection} is not a list`);
  return validated({
    selection,
    numbers: list.map((n) => positiveInteger(n, selection)),
    exclude: flag(record, 'exclude'),
    preflightOnly: flag(record, 'preflightOnly'),
    maxSlices:
      record['maxSlices'] === undefined
        ? MAX_SLICES
        : positiveInteger(record['maxSlices'], 'maxSlices'),
  });
}
function parseJson(text) {
  try {
    return JSON.parse(text);
  } catch {
    throw new ArgsError('not valid JSON');
  }
}
function numberList(token) {
  if (token.startsWith('--')) throw new ArgsError(`unknown flag '${token}'`);
  return token
    .split(',')
    .filter((piece) => piece !== '')
    .map((piece) => positiveInteger(piece.replace(/^#/, ''), piece));
}
function positiveInteger(value, what) {
  const n = typeof value === 'string' && /^\d+$/.test(value) ? Number(value) : value;
  if (typeof n !== 'number' || !Number.isInteger(n) || n < 1) {
    throw new ArgsError(`${what}: '${String(value)}' is not a positive integer`);
  }
  return n;
}
function flag(record, key) {
  const value = record[key];
  if (value === undefined) return false;
  if (typeof value !== 'boolean') throw new ArgsError(`${key} is not a boolean`);
  return value;
}
function validated(args) {
  if (args.numbers.length === 0) throw new ArgsError(`no ${args.selection} numbers`);
  const twice = args.numbers.find((n, i) => args.numbers.indexOf(n) !== i);
  if (twice !== undefined) throw new ArgsError(`#${String(twice)} is given twice`);
  return args;
}

function runSetIssues(runSet) {
  const all = new Set();
  for (const entry of runSet) {
    for (const issue of entry.issues) all.add(issue);
  }
  return [...all].sort((a, b) => a - b);
}
function findCycles(issues, edges) {
  const adj = adjacency(issues, edges);
  const cycles = stronglyConnected(adj).filter(
    (c) => c.length > 1 || c.some((n) => adj.get(n)?.includes(n) === true),
  );
  for (const cycle of cycles) cycle.sort((a, b) => a - b);
  cycles.sort((a, b) => (a[0] ?? 0) - (b[0] ?? 0));
  return cycles;
}
function transitiveDependents(roots, edges) {
  const next = new Map();
  for (const e of edges) {
    const out = next.get(e.blocker) ?? [];
    out.push(e.dependent);
    next.set(e.blocker, out);
  }
  const seen = new Set(roots);
  const reached = [];
  const walk = (v) => {
    for (const w of next.get(v) ?? []) {
      if (seen.has(w)) continue;
      seen.add(w);
      reached.push(w);
      walk(w);
    }
  };
  for (const r of roots) walk(r);
  return reached.sort((a, b) => a - b);
}
function adjacency(issues, edges) {
  const adj = new Map();
  for (const n of issues) adj.set(n, []);
  for (const e of edges) {
    if (adj.has(e.dependent)) adj.get(e.blocker)?.push(e.dependent);
  }
  return adj;
}
function stronglyConnected(adj) {
  const visited = new Map();
  const stack = [];
  const onStack = new Set();
  const components = [];
  const popComponent = (root) => {
    const component = [];
    for (let w = stack.pop(); w !== undefined; w = w === root ? undefined : stack.pop()) {
      onStack.delete(w);
      component.push(w);
    }
    return component;
  };
  const visit = (v) => {
    const node = { index: visited.size, low: visited.size };
    visited.set(v, node);
    stack.push(v);
    onStack.add(v);
    for (const w of adj.get(v) ?? []) {
      const seen = visited.get(w);
      if (seen === undefined) node.low = Math.min(node.low, visit(w).low);
      else if (onStack.has(w)) node.low = Math.min(node.low, seen.index);
    }
    if (node.low === node.index) components.push(popComponent(v));
    return node;
  };
  for (const v of adj.keys()) if (!visited.has(v)) visit(v);
  return components;
}

const ACCEPTED_PHASES = {
  committed: ['authoring', 'landing'],
  blocked: ['authoring', 'landing'],
  'harvest-conflict': ['authoring', 'landing'],
  'agent-died': ['authoring', 'landing'],
  'slot-free': ['authoring'],
  'label-removed': ['waiting', 'ready', 'authoring', 'landing'],
};
const SETTLED_PHASES = ['committed', 'blocked', 'removed', 'skipped', 'halted'];
function createScheduler(input) {
  assertInput(input);
  const state = initialState(input);
  return finish(state, openDraft(state));
}
function advance(state, event) {
  const draft = openDraft(state);
  if (event.kind === 'epic-halt') onEpicHalt(draft, state, event.epic);
  else onIssueEvent(draft, state, event);
  return finish(state, draft);
}
function onIssueEvent(draft, state, event) {
  assertPhase(state, event);
  const issue = event.issue;
  if (
    state.halted[entryIndexOf(state, issue)] === true &&
    settleInHaltedEntry(draft, state, event)
  ) {
    return;
  }
  switch (event.kind) {
    case 'committed':
      onCommitted(draft, state, issue);
      break;
    case 'blocked':
      settleAndSkip(draft, state, issue, 'blocked');
      break;
    case 'harvest-conflict':
      restart(draft, { kind: 'requeue', issue });
      break;
    case 'agent-died':
      onAgentDied(draft, state, issue);
      break;
    case 'label-removed':
      onLabelRemoved(draft, state, issue);
      break;
    case 'slot-free':
      draft.phase[issue] = 'landing';
      break;
  }
}
function settleInHaltedEntry(draft, state, event) {
  if (event.kind === 'committed') {
    const { epic } = state.runSet[entryIndexOf(state, event.issue)] ?? { epic: null };
    fail(`committed for ${hash(event.issue)}, whose ${entryLabel(epic)} is halted`);
  }
  if (event.kind === 'slot-free' || event.kind === 'label-removed') return false;
  draft.phase[event.issue] = 'halted';
  return true;
}
function onEpicHalt(draft, state, epic) {
  const index = state.runSet.findIndex((entry) => entry.epic === epic);
  const subject = `epic-halt for ${entryLabel(epic)}`;
  if (index < 0) fail(`${subject}, which is not in the run`);
  if (state.halted[index] === true) fail(`${subject}, which is halted`);
  if (state.epicDone[index] === true) fail(`${subject}, which is done`);
  draft.halted[index] = true;
  for (const issue of state.runSet[index]?.issues ?? []) {
    if (draft.phase[issue] !== 'waiting' && draft.phase[issue] !== 'ready') continue;
    draft.phase[issue] = 'halted';
    dequeue(draft, issue);
  }
}
function entryIndexOf(state, issue) {
  return state.runSet.findIndex((entry) => entry.issues.includes(issue));
}
function assertInput(input) {
  const { maxSlices, runSet, edges } = input;
  if (!Number.isInteger(maxSlices) || maxSlices < 1) {
    fail(`maxSlices must be an integer of 1 or more, got ${String(maxSlices)}`);
  }
  for (const entry of runSet) {
    if (entry.issues.length === 0) fail(`the entry for ${entryLabel(entry.epic)} has no issues`);
  }
  const entryOf = entryIndexByIssue(runSet);
  assertDistinctEpics(runSet);
  assertEdgesInEntries(edges, entryOf);
  const cycles = findCycles(runSetIssues(runSet), edges);
  if (cycles.length > 0) {
    fail(`dependency cycle among ${cycles.map((c) => c.map(hash).join(', ')).join('; ')}`);
  }
}
function entryIndexByIssue(runSet) {
  const entryOf = new Map();
  runSet.forEach((entry, index) => {
    for (const issue of entry.issues) {
      if (entryOf.has(issue)) fail(`issue ${hash(issue)} appears more than once in the run set`);
      entryOf.set(issue, index);
    }
  });
  return entryOf;
}
function assertDistinctEpics(runSet) {
  const seen = new Set();
  for (const { epic } of runSet) {
    if (seen.has(epic))
      fail(`two entries share the epic key ${epic === null ? 'null' : hash(epic)}`);
    seen.add(epic);
  }
}
function assertEdgesInEntries(edges, entryOf) {
  for (const e of edges) {
    const outside = [e.blocker, e.dependent].find((issue) => !entryOf.has(issue));
    if (outside !== undefined) {
      fail(`edge ${edgeLabel(e)} names ${hash(outside)}, which is outside the run set`);
    }
  }
  for (const e of edges) {
    if (entryOf.get(e.blocker) !== entryOf.get(e.dependent)) {
      fail(`edge ${edgeLabel(e)} crosses run-set entries`);
    }
  }
}
function initialState(input) {
  const runSet = input.runSet.map((entry) => ({ epic: entry.epic, issues: [...entry.issues] }));
  const order = runSet.flatMap((entry) => entry.issues);
  const edges = dedupeEdges(input.edges);
  const blockers = {};
  const phase = {};
  for (const issue of order) blockers[issue] = [];
  for (const e of edges) blockers[e.dependent]?.push(e.blocker);
  for (const issue of order) phase[issue] = blockers[issue]?.length ? 'waiting' : 'ready';
  return {
    maxSlices: input.maxSlices,
    runSet,
    edges,
    order,
    blockers,
    phase,
    retried: {},
    ready: order.filter((issue) => phase[issue] === 'ready'),
    epicDone: runSet.map(() => false),
    halted: runSet.map(() => false),
  };
}
function dedupeEdges(edges) {
  const seen = new Set();
  const out = [];
  for (const e of edges) {
    const key = `${String(e.blocker)}>${String(e.dependent)}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push({ blocker: e.blocker, dependent: e.dependent });
  }
  return out;
}
function assertPhase(state, event) {
  const phase = state.phase[event.issue];
  const subject = `${event.kind} for ${hash(event.issue)}`;
  if (!Object.hasOwn(ACCEPTED_PHASES, event.kind)) fail(`unknown event ${subject}`);
  if (phase === undefined) fail(`${subject}, which is not in the run`);
  if (!ACCEPTED_PHASES[event.kind].includes(phase)) fail(`${subject}, which is ${phase}`);
}
function openDraft(state) {
  return {
    phase: { ...state.phase },
    retried: { ...state.retried },
    ready: [...state.ready],
    epicDone: [...state.epicDone],
    halted: [...state.halted],
    response: [],
    skips: [],
    starts: [],
    ends: [],
  };
}
function finish(state, draft) {
  fill(draft, state);
  emitEnds(draft, state);
  return {
    state: {
      ...state,
      phase: draft.phase,
      retried: draft.retried,
      ready: draft.ready,
      epicDone: draft.epicDone,
      halted: draft.halted,
    },
    actions: [...draft.response, ...draft.skips, ...draft.starts, ...draft.ends],
  };
}
function onCommitted(draft, state, issue) {
  draft.phase[issue] = 'committed';
  for (const candidate of state.order) {
    if (draft.phase[candidate] !== 'waiting') continue;
    const blockers = state.blockers[candidate] ?? [];
    if (blockers.every((b) => draft.phase[b] === 'committed')) {
      draft.phase[candidate] = 'ready';
      draft.ready.push(candidate);
    }
  }
}
function onAgentDied(draft, state, issue) {
  if (draft.retried[issue]) {
    draft.response.push({ kind: 'block', issue, reason: 'retry-exhausted' });
    settleAndSkip(draft, state, issue, 'retry-exhausted');
    return;
  }
  draft.retried[issue] = true;
  restart(draft, { kind: 'retry', issue });
}
function onLabelRemoved(draft, state, issue) {
  dequeue(draft, issue);
  settleAndSkip(draft, state, issue, 'label-removed');
}
function dequeue(draft, issue) {
  const queued = draft.ready.indexOf(issue);
  if (queued >= 0) draft.ready.splice(queued, 1);
}
function restart(draft, response) {
  draft.response.push(response);
  draft.phase[response.issue] = 'ready';
  draft.ready.unshift(response.issue);
}
function settleAndSkip(draft, state, root, trigger) {
  draft.phase[root] = trigger === 'label-removed' ? 'removed' : 'blocked';
  for (const issue of transitiveDependents([root], state.edges)) {
    if (draft.phase[issue] !== 'waiting') continue;
    draft.phase[issue] = 'skipped';
    draft.skips.push({ kind: 'skip', issue, cause: { root, trigger } });
  }
}
function fill(draft, state) {
  let authoring = state.order.filter((issue) => draft.phase[issue] === 'authoring').length;
  while (authoring < state.maxSlices) {
    const next = draft.ready.shift();
    if (next === undefined) return;
    draft.phase[next] = 'authoring';
    draft.starts.push({ kind: 'start', issue: next });
    authoring += 1;
  }
}
function emitEnds(draft, state) {
  state.runSet.forEach((entry, index) => {
    if (draft.epicDone[index] === true) return;
    const phases = entry.issues.map((issue) => draft.phase[issue]);
    if (!phases.every((p) => p !== undefined && SETTLED_PHASES.includes(p))) return;
    draft.epicDone[index] = true;
    const kind = draft.halted[index] === true ? 'epic-halted' : 'epic-done';
    draft.ends.push({ kind, epic: entry.epic });
  });
}
function fail(message) {
  throw new Error(`run scheduler: ${message}`);
}
function hash(issue) {
  return `#${String(issue)}`;
}
function edgeLabel(e) {
  return `${hash(e.blocker)} -> ${hash(e.dependent)}`;
}
function entryLabel(epic) {
  return epic === null ? 'the explicit list' : `epic ${hash(epic)}`;
}

