const CRITIC_TAG = 'critic';
async function criticStep(input) {
  if (input.landed.length < 2) return { outcome: 'skipped', findings: [], halt: null };
  const { hooks, entry } = input;
  const place = runPlace(entry.reportDir, CRITIC_TAG);
  const argv = [entry.batch, '--critic', ...attachedRunArgs(entry)];
  const cut = await runTool(hooks, 'cut-slice', argv, place).catch(() => null);
  const slice = typeof cut?.slice === 'string' ? cut.slice : null;
  const base = cut?.base;
  if (cut?.status !== 'ok' || slice === null || typeof base !== 'string') {
    return criticTornDown(input, slice, criticNotRun(envelopeProblem('cut-slice', cut)));
  }
  const result = await criticInSlice(input, slice, base).catch((err) =>
    criticNotRun(`the critic step threw: ${err instanceof Error ? err.message : String(err)}`),
  );
  return criticTornDown(input, slice, result);
}
async function criticInSlice(input, slice, base) {
  const { hooks, entry } = input;
  const argv = [slice, '--batch', entry.batch];
  const prov = await runTool(hooks, 'provision', argv, runPlace(entry.reportDir, CRITIC_TAG));
  if (prov?.status !== 'ok') return criticNotRun(envelopeProblem('provision', prov));
  const values = {
    slice,
    range: `${entry.base}..HEAD`,
    landed: input.landed.map((l) => ({ issue: l.issue, commit: l.commit, plan: l.card.planPath })),
    reportPath: `${entry.reportDir}/critic.md`,
  };
  const out = await AGENT_CALLS.critic(hooks, values, entry.tag);
  if (out === null) return criticNotRun('the critic returned nothing');
  if (out.outcome === 'clean') return { outcome: 'clean', findings: out.findings, halt: null };
  if (out.sha === '') {
    return {
      outcome: 'dropped',
      reason: 'the critic applied no commit',
      findings: out.findings,
      halt: null,
    };
  }
  return criticLand(input, out, base);
}
async function criticLand(input, out, base) {
  const { hooks, entry } = input;
  const messagePath = `${entry.reportDir}/commit-critic.txt`;
  const argv = [
    entry.batch,
    out.sha,
    '--base',
    base,
    '--message-file',
    messagePath,
    '--log',
    `${entry.reportDir}/land-critic.log`,
  ];
  const write = { path: messagePath, content: criticCommitMessage(out.commit) };
  const place = runPlace(entry.reportDir, CRITIC_TAG, write);
  const land = await runTool(hooks, 'land', argv, place).catch(() => null);
  const kind = classifyLanding(land);
  if (kind === 'committed' && typeof land?.commit === 'string') {
    return { outcome: 'landed', commit: land.commit, findings: out.findings, halt: null };
  }
  const reason = envelopeProblem('land', land);
  return {
    outcome: 'dropped',
    reason,
    findings: out.findings,
    halt: kind === 'halt' ? reason : null,
  };
}
async function criticTornDown(input, slice, result) {
  if (slice === null) return result;
  const place = runPlace(input.entry.reportDir, CRITIC_TAG);
  const teardown = await runTool(input.hooks, 'teardown', [slice], place).catch(() => null);
  const halt = teardownEvent(teardown, input.entry.epic);
  return halt === null || result.halt !== null ? result : { ...result, halt: halt.reason };
}
function criticNotRun(reason) {
  return { outcome: 'not-run', reason, findings: [], halt: null };
}

const NO_LAUNCH = 'no launch snapshot of master to check against';
const NO_SYNCED = 'master sync named no origin/master sha to check against';
async function checkMasterStep(hooks, entry, launch, synced) {
  if (launch === null) return { passed: false, local: null, remote: null, failure: NO_LAUNCH };
  if (synced === null) return { passed: false, local: null, remote: null, failure: NO_SYNCED };
  const { master } = launch.snapshot;
  const out = await runTool(
    hooks,
    'check-master',
    [entry.main, '--local', master.local, '--remote', master.remote, '--synced', synced],
    runPlace(entry.reportDir, entry.tag),
  );
  return checkOf(out);
}
function checkOf(out) {
  const local = out?.local ?? null;
  const remote = out?.remote ?? null;
  if (out?.status === 'ok' && isForward(local) && isForward(remote)) {
    return { passed: true, local, remote };
  }
  return { passed: false, local, remote, failure: failureOf(out, local, remote) };
}
function failureOf(out, local, remote) {
  const lines = [
    ...(local === null || isForward(local) ? [] : [moveLine('local', local)]),
    ...(remote === null || isForward(remote) ? [] : [moveLine('origin', remote)]),
  ];
  if (out?.status === 'refused' && out.reason === 'master-not-forward' && lines.length > 0) {
    return lines.join('; ');
  }
  return envelopeProblem('check-master', out);
}
function isForward(move) {
  return (
    move !== null && (move.move === 'equal' || move.move === 'forward') && move.current !== null
  );
}
function moveLine(which, move) {
  const synced = move.synced === null ? '' : `, synced ${move.synced}`;
  return (
    `${which} master ${move.move}: launch ${move.launch}${synced}, now ${move.current ?? 'deleted'}` +
    ` — restore it from ${move.synced ?? move.launch}`
  );
}

async function syncMasterStep(hooks, ctx) {
  const start = await runTool(hooks, 'sync-master', [ctx.batch], runPlace(ctx.reportDir, ctx.tag));
  const found = { conflicts: start?.conflicts ?? [], version: start?.version ?? null };
  if (start?.status === 'conflict' && start.outcome === 'needs-resolution') {
    return { ...(await resolveAndContinue(hooks, ctx, start.pending ?? [])), ...found };
  }
  return { ...syncVerdict(start, 'merged'), ...found };
}
async function resolveAndContinue(hooks, ctx, pending) {
  if (pending.length === 0) {
    return syncFailure(
      `sync-master needs resolution but named no path; merge left in ${ctx.batch}`,
    );
  }
  const values = { batch: ctx.batch, pending, reportPath: `${ctx.reportDir}/resolve.md` };
  const answer = await AGENT_CALLS.resolver(hooks, values, ctx.tag);
  if (answer?.verdict !== 'resolved') {
    const said = answer === null ? 'returned nothing' : `said ${answer.summary}`;
    return syncFailure(`the resolver ${said}; merge left in progress in ${ctx.batch}`);
  }
  const done = await runTool(
    hooks,
    'sync-master',
    [ctx.batch, '--continue'],
    runPlace(ctx.reportDir, `${ctx.tag}-continue`),
  );
  return syncVerdict(done, 'resolved');
}
function syncVerdict(out, merged) {
  if (out?.status === 'ok' && out.outcome === 'up-to-date') {
    return {
      verdict: 'up-to-date',
      commit: null,
      upstream: out.upstream ?? null,
      message: 'origin/master already merged',
    };
  }
  if (out?.status === 'ok' && out.outcome === 'merged' && typeof out.commit === 'string') {
    return {
      verdict: merged,
      commit: out.commit,
      upstream: out.upstream ?? null,
      message: `merged origin/master as ${out.commit}`,
    };
  }
  const message = envelopeProblem('sync-master', out);
  if (out?.status === 'refused' && out.reason === 'code-conflict') {
    return { verdict: 'code-conflict', commit: null, upstream: null, message };
  }
  return syncFailure(message);
}
function syncFailure(message) {
  return { verdict: 'failed', commit: null, upstream: null, message };
}

async function epicEnd(input) {
  const state = {};
  const published = await shipSteps(input, state).catch((err) => ({
    outcome: 'stopped',
    message: `the epic end threw: ${err instanceof Error ? err.message : String(err)}`,
  }));
  const issueComments = await commentBlockedStep(input, published.pr);
  if (state.retro === undefined)
    state.retro = await retroStep(input, retroReport(input, published));
  return {
    epic: input.entry.epic,
    branch: input.entry.branch,
    ...published,
    issues: input.issues,
    schedule: input.schedule,
    mainUntouched: await mainAtEnd(input, state),
    ...(state.masterCheck === undefined ? {} : { masterCheck: state.masterCheck }),
    residue: input.residue,
    ...(state.critic === undefined ? {} : { critic: state.critic }),
    retro: state.retro,
    ...(state.leases === undefined ? {} : { leases: state.leases }),
    ...(issueComments.length === 0 ? {} : { issueComments }),
  };
}
async function unshippedEpicEnd(input, outcome) {
  const issueComments = await commentBlockedStep(input, undefined);
  const report = {
    epic: input.entry.epic,
    branch: input.entry.branch,
    outcome,
    issues: input.issues,
    schedule: input.schedule,
    residue: input.residue,
    ...(issueComments.length === 0 ? {} : { issueComments }),
  };
  return { ...report, retro: await retroStep(input, report) };
}
async function commentBlockedStep(input, pr) {
  const { entry } = input;
  const comments = [];
  for (const issue of input.issues) {
    if (issue.outcome !== 'blocked') continue;
    const path = `${entry.reportDir}/issue-comment-${String(issue.issue)}.md`;
    const content = renderBlockedComment({
      issue: issue.issue,
      ...(issue.reason === undefined ? {} : { reason: issue.reason }),
      ...(pr === undefined ? {} : { pr }),
      branch: entry.branch,
      reportDir: entry.reportDir,
    });
    const argv = [entry.main, '--issue', String(issue.issue), '--comment-file', path];
    const place = runPlace(entry.reportDir, String(issue.issue), { path, content });
    comments.push(await postIssueComment(input.hooks, issue.issue, argv, place));
  }
  return comments;
}
async function postIssueComment(hooks, issue, argv, place) {
  try {
    const out = await runTool(hooks, 'post-issue-comment', argv, place);
    if (out?.status !== 'ok') {
      return { issue, url: null, problem: envelopeProblem('post-issue-comment', out) };
    }
    return typeof out.url === 'string'
      ? { issue, url: out.url }
      : { issue, url: null, problem: 'post-issue-comment ok without a url' };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return { issue, url: null, problem: `post-issue-comment threw: ${message}` };
  }
}
async function shipSteps(input, state) {
  const { hooks, entry } = input;
  const critic = await criticStep(input);
  const { halt, ...criticReport } = critic;
  state.critic = criticReport;
  state.leases = leaseTotals(input.landed);
  if (halt !== null) return { outcome: 'halted', message: `the critic halted the epic: ${halt}` };
  const sync = await input.repoLock.enqueue(() => syncMasterStep(hooks, entry));
  if (sync.verdict === 'code-conflict' || sync.verdict === 'failed') {
    return { outcome: 'stopped', message: `master sync ${sync.verdict}: ${sync.message}` };
  }
  const bump = await runTool(hooks, 'bump', [entry.batch], runPlace(entry.reportDir, entry.tag));
  if (bump?.status !== 'ok') return { outcome: 'stopped', message: envelopeProblem('bump', bump) };
  await hooks.parallel([
    async () => {
      state.retro = await retroStep(input, retroReport(input, { outcome: 'pr' }));
    },
    async () => {
      if (entry.attachedRun === null) state.writer = await prWriterStep(input, sync.upstream);
    },
  ]);
  return publishStep(input, { sync, bump, state });
}
async function publishStep(input, found) {
  return input.repoLock.enqueue(async () => {
    const untouched = await mainUntouched(input);
    found.state.mainUntouched = untouched;
    const check = await checkMasterStep(
      input.hooks,
      input.entry,
      input.launch,
      found.sync.upstream,
    );
    found.state.masterCheck = check;
    if (!check.passed)
      return { outcome: 'stopped', message: `master check failed: ${check.failure}` };
    const checked = { masterCheck: check, mainUntouched: untouched };
    if (input.entry.attachedRun !== null) {
      return pushOntoPr(input, found, checked, input.entry.attachedRun);
    }
    return openPr(input, found, checked);
  });
}
async function pushOntoPr(input, found, checked, run) {
  const { hooks, entry } = input;
  const argv = [entry.batch, '--push-only', '--log', `${entry.reportDir}/publish.log`];
  const out = await runTool(hooks, 'publish', argv, runPlace(entry.reportDir, entry.tag));
  const published = publishedPr(out);
  if (published.outcome !== 'pr' || published.pr === undefined) return published;
  const base = { ...bodyInput(input, found, checked), run };
  const posted = await postReportStep(input, published.pr, renderAttachedReport(base));
  const reportComment = 'url' in posted ? posted.url : null;
  const section = renderAttachedSection({ ...base, reportComment });
  const failure = await appendSectionStep(input, published.pr, section);
  return {
    ...published,
    ...('failure' in posted ? { prReportComment: posted.failure } : {}),
    ...(failure === null ? {} : { prBodyEdit: failure }),
  };
}
async function postReportStep(input, pr, report) {
  const file = { name: 'pr-report-comment.md', flag: '--comment-file', content: report };
  const posted = await prFileStep(input, 'post-pr-comment', pr, file);
  if ('failure' in posted) return posted;
  return typeof posted.ok.url === 'string'
    ? { url: posted.ok.url }
    : { failure: 'post-pr-comment ok without a url' };
}
async function appendSectionStep(input, pr, section) {
  const file = { name: 'pr-section.md', flag: '--section-file', content: section };
  const edited = await prFileStep(input, 'append-pr-body', pr, file);
  return 'failure' in edited ? edited.failure : null;
}
async function prFileStep(input, tool, pr, file) {
  const { hooks, entry } = input;
  const path = `${entry.reportDir}/${file.name}`;
  const argv = [entry.batch, '--pr', String(pr), file.flag, path];
  const place = runPlace(entry.reportDir, entry.tag, { path, content: file.content });
  try {
    const out = await runTool(hooks, tool, argv, place);
    return out?.status === 'ok' ? { ok: out } : { failure: envelopeProblem(tool, out) };
  } catch (err) {
    return { failure: `${tool} threw: ${err instanceof Error ? err.message : String(err)}` };
  }
}
function publishedPr(out) {
  const pr = out?.status === 'ok' ? out.pr : null;
  if (pr === undefined || pr === null) {
    return { outcome: 'stopped', message: envelopeProblem('publish', out) };
  }
  return { outcome: 'pr', pr: pr.number };
}
async function openPr(input, found, checked) {
  const { hooks, entry } = input;
  const body = renderPrBody({
    ...bodyInput(input, found, checked),
    writer: found.state.writer ?? null,
  });
  const bodyPath = `${entry.reportDir}/pr-body.md`;
  const argv = [
    entry.batch,
    '--title',
    prTitle({ branch: entry.branch, landed: input.landed }),
    '--body-file',
    bodyPath,
    '--log',
    `${entry.reportDir}/publish.log`,
  ];
  const place = runPlace(entry.reportDir, entry.tag, { path: bodyPath, content: body });
  const out = await runTool(hooks, 'publish', argv, place);
  return publishedPr(out);
}
function bodyInput(input, found, checked) {
  const { entry } = input;
  return {
    epic: entry.epic,
    branch: entry.branch,
    reportDir: entry.reportDir,
    landed: input.landed,
    unlanded: input.issues.filter((i) => i.outcome !== 'landed'),
    sync: found.sync,
    bump: found.bump,
    masterCheck: checked.masterCheck,
    mainUntouched: checked.mainUntouched,
    critic: found.state.critic ?? { outcome: 'not-run', reason: 'no critic step', findings: [] },
    overlap: input.overlap,
    schedule: input.schedule,
    leases: found.state.leases ?? leaseTotals(input.landed),
    retro: found.state.retro ?? null,
  };
}
function leaseTotals(landed) {
  return aggregateLeaseTimings(
    landed.flatMap((l) =>
      sliceLeaseLines(l).flatMap((r) => r.lines.map((line) => ({ issue: l.issue, line }))),
    ),
  );
}
async function retroStep(input, report) {
  const { entry } = input;
  const values = { epic: entry.epic, reportDir: entry.reportDir, report };
  const out = await AGENT_CALLS.retro(input.hooks, values, entry.tag).catch(() => null);
  return out?.findings ?? null;
}
async function prWriterStep(input, upstream) {
  const { entry } = input;
  const values = {
    epic: entry.epic,
    batch: entry.batch,
    range: `${upstream ?? entry.base}...HEAD`,
    landed: input.landed.map((l) => ({
      issue: l.issue,
      commit: l.commit,
      plan: l.card.planPath,
      subject: l.card.commit.subject,
    })),
    reportDir: entry.reportDir,
  };
  return AGENT_CALLS.prWriter(input.hooks, values, entry.tag).catch(() => null);
}
function retroReport(input, published) {
  return {
    epic: input.entry.epic,
    branch: input.entry.branch,
    ...published,
    issues: input.issues,
    schedule: input.schedule,
    residue: input.residue,
  };
}
async function mainAtEnd(input, state) {
  if (state.mainUntouched !== undefined) return state.mainUntouched;
  return input.repoLock.enqueue(() => mainUntouched(input));
}
async function mainUntouched(input) {
  const { entry, launch } = input;
  const out = await runTool(
    input.hooks,
    'preflight',
    [entry.main],
    runPlace(entry.reportDir, entry.tag),
  );
  const now = out?.snapshot;
  if (launch === null || now === undefined || now === null) return null;
  return now.head === launch.snapshot.head && now.dirty === launch.snapshot.dirty;
}

async function drive(input) {
  const d = newDrive(input);
  apply(d, createScheduler({ ...input.graph, maxSlices: input.maxSlices }));
  while (d.flights.size > 0) {
    const note = await Promise.race(d.flights.values());
    d.flights.delete(flightKey(note));
    onNote(d, note);
  }
  return input.entries.map((_entry, i) => entryReport(d, i));
}
function newDrive(input) {
  const d = {
    input,
    contexts: [],
    scheduler: null,
    flights: new Map(),
    attempts: new Map(),
    conflicts: new Map(),
    timing: new Map(),
    halts: new Map(),
    outcomes: new Map(),
    landed: new Map(),
    residue: new Map(),
    ends: new Map(),
    repoLock: createCommitQueue(),
    epicEndEntered: false,
  };
  input.entries.forEach((entry, i) => {
    d.contexts.push({
      ...entry,
      hooks: input.hooks,
      queue: createCommitQueue(),
      isHalting: () => haltOf(d, i) !== 'running',
      markHalting: () => {
        if (haltOf(d, i) === 'running') d.halts.set(i, 'halting');
      },
      priorSlices: () =>
        (d.landed.get(i) ?? []).map((l) => ({
          issue: l.issue,
          commit: l.commit,
          plan: l.card.planPath,
        })),
    });
  });
  return d;
}
function haltOf(d, i) {
  return d.halts.get(i) ?? 'running';
}
function flightKey(note) {
  return note.kind === 'epic-end' ? `epic:${String(note.entry)}` : `issue:${String(note.issue)}`;
}
function onNote(d, note) {
  if (note.kind === 'epic-end') {
    d.ends.set(note.entry, note.report);
  } else if (note.kind === 'authored') {
    d.flights.set(flightKey(note), note.landing);
  } else {
    settle(d, note.issue, note.ending);
  }
}
function settle(d, issue, ending) {
  const i = entryOfIssue(d, issue);
  const epic = d.input.entries[i]?.epic ?? null;
  const { events, entry } = settleEvents(ending.primary, ending.halt, {
    issue,
    epic,
    entry: haltOf(d, i),
  });
  d.halts.set(i, entry);
  if (ending.residue !== null) d.residue.set(i, [...(d.residue.get(i) ?? []), ending.residue]);
  d.conflicts.set(issue, ending.conflicts);
  d.timing.set(issue, {
    attempts: d.attempts.get(issue) ?? 1,
    startedAt: ending.startedAt,
    committedAt: ending.committedAt,
    size: ending.size,
  });
  record(d, i, issue, ending, events);
  feed(d, events);
}
function record(d, i, issue, ending, events) {
  const { work, commit } = ending;
  if (events.some((e) => e.kind === 'committed') && work !== null && commit !== null) {
    d.landed.set(i, [...(d.landed.get(i) ?? []), { ...work, issue, commit }]);
    d.outcomes.set(issue, { issue, outcome: 'landed', cite: work.card.closes, commit });
    return;
  }
  const report = unlandedOutcome(issue, ending, haltOf(d, i) === 'halted');
  if (report !== null) d.outcomes.set(issue, report);
}
function unlandedOutcome(issue, ending, halted) {
  const { primary, commit } = ending;
  const reason = 'reason' in primary ? primary.reason : undefined;
  if (primary.kind === 'committed' && commit !== null) {
    return { issue, outcome: 'landed-then-halted', cite: 'see', commit };
  }
  if (halted)
    return { issue, outcome: 'halted', cite: 'see', ...(reason === undefined ? {} : { reason }) };
  if (primary.kind === 'blocked')
    return { issue, outcome: 'blocked', cite: 'see', reason: primary.reason };
  if (primary.kind === 'label-removed') {
    return { issue, outcome: 'removed', cite: 'see', reason: 'no longer open and ready-for-agent' };
  }
  return null;
}
function feed(d, events) {
  for (const event of events) {
    d.input.hooks.log(`fed ${event.kind} ${eventSubject(event)}`);
    if (d.scheduler === null) throw new Error('ship: fed an event before the scheduler started');
    apply(d, advance(d.scheduler, event));
  }
}
function apply(d, t) {
  d.scheduler = t.state;
  for (const action of t.actions) act(d, action);
}
function act(d, action) {
  switch (action.kind) {
    case 'start':
      startAttempt(d, action.issue);
      break;
    case 'requeue':
    case 'retry':
      d.attempts.set(action.issue, (d.attempts.get(action.issue) ?? 1) + 1);
      break;
    case 'skip':
      d.outcomes.set(action.issue, {
        issue: action.issue,
        outcome: 'skipped',
        cite: 'see',
        reason: `blocker #${String(action.cause.root)} ${action.cause.trigger}`,
      });
      break;
    case 'block':
      d.outcomes.set(action.issue, {
        issue: action.issue,
        outcome: 'blocked',
        cite: 'see',
        reason: 'its agent died on the retry too',
      });
      break;
    case 'epic-done':
      endEpic(d, entryOfEpic(d, action.epic));
      break;
    case 'epic-halted':
      endUnshipped(d, entryOfEpic(d, action.epic), 'halted');
      break;
  }
}
function startAttempt(d, issue) {
  const ctx = d.contexts[entryOfIssue(d, issue)];
  if (ctx === undefined) throw new Error(`ship: no entry holds #${String(issue)}`);
  const attempt = d.attempts.get(issue) ?? 1;
  d.input.hooks.log(`start #${String(issue)} attempt ${String(attempt)}`);
  const conflicts = d.conflicts.get(issue) ?? [];
  d.flights.set(`issue:${String(issue)}`, runAttempt(ctx, issue, attempt, conflicts));
}
function endEpic(d, i) {
  const landed = d.landed.get(i) ?? [];
  const entry = d.input.entries[i];
  if (landed.length === 0 || entry === undefined) {
    endUnshipped(d, i, 'nothing-landed');
    return;
  }
  const issues = issueReports(d, i);
  const residue = d.residue.get(i) ?? [];
  const schedule = scheduleOf(d, i);
  const report = epicEnd({
    hooks: d.input.hooks,
    entry,
    landed,
    issues,
    schedule,
    residue,
    launch: d.input.launch,
    repoLock: d.repoLock,
    overlap: entryOverlap(d, i),
  }).catch((err) => ({
    epic: entry.epic,
    branch: entry.branch,
    outcome: 'stopped',
    message: `the epic end threw: ${err instanceof Error ? err.message : String(err)}`,
    issues,
    schedule,
    residue,
  }));
  startEnd(d, i, report);
}
function endUnshipped(d, i, outcome) {
  const entry = d.input.entries[i];
  if (entry === undefined) return;
  const input = {
    hooks: d.input.hooks,
    entry,
    issues: issueReports(d, i),
    schedule: scheduleOf(d, i),
    residue: d.residue.get(i) ?? [],
  };
  const report = unshippedEpicEnd(input, outcome).catch(() => ({
    epic: entry.epic,
    branch: entry.branch,
    outcome,
    issues: input.issues,
    schedule: input.schedule,
    residue: input.residue,
    retro: null,
  }));
  startEnd(d, i, report);
}
function startEnd(d, i, report) {
  if (!d.epicEndEntered) d.input.hooks.phase(PHASE_TITLES.epicEnd);
  d.epicEndEntered = true;
  d.flights.set(
    `epic:${String(i)}`,
    report.then((r) => ({ kind: 'epic-end', entry: i, report: r })),
  );
}
function entryReport(d, i) {
  const end = d.ends.get(i);
  if (end !== undefined) return end;
  const entry = d.input.entries[i];
  return {
    epic: entry?.epic ?? null,
    branch: entry?.branch ?? '',
    outcome: 'halted',
    issues: issueReports(d, i),
    schedule: scheduleOf(d, i),
    residue: d.residue.get(i) ?? [],
  };
}
function issueReports(d, i) {
  const issues = d.input.graph.runSet[i]?.issues ?? [];
  return issues.map((issue) => d.outcomes.get(issue) ?? { issue, outcome: 'halted', cite: 'see' });
}
function scheduleOf(d, i) {
  const issues = d.input.graph.runSet[i]?.issues ?? [];
  return issues.map((issue) => ({
    ...neverStarted(issue, d.input.graph, d.input.overlap),
    ...d.timing.get(issue),
  }));
}
function neverStarted(issue, graph, overlap) {
  const blockers = graph.edges
    .filter((e) => e.dependent === issue)
    .map((e) => e.blocker)
    .sort((a, b) => a - b)
    .map((blocker) => scheduleBlocker(blocker, issue, overlap));
  return { issue, blockers, attempts: 0, startedAt: null, committedAt: null, size: null };
}
function scheduleBlocker(blocker, dependent, overlap) {
  const added = overlap.added.find((e) => e.blocker === blocker && e.dependent === dependent);
  if (added === undefined) return { issue: blocker, source: 'declared' };
  return { issue: blocker, source: 'overlap', confidence: added.confidence };
}
function entryOverlap(d, i) {
  const issues = new Set(d.input.graph.runSet[i]?.issues ?? []);
  const { overlap } = d.input;
  return {
    added: overlap.added.filter((e) => issues.has(e.blocker)),
    sequenced: overlap.sequenced.filter((p) => issues.has(p.a)),
    areaMap: overlap.areaMap,
  };
}
function entryOfIssue(d, issue) {
  return d.input.graph.runSet.findIndex((entry) => entry.issues.includes(issue));
}
function entryOfEpic(d, epic) {
  return d.input.graph.runSet.findIndex((entry) => entry.epic === epic);
}
function eventSubject(event) {
  if (event.kind !== 'epic-halt') return `#${String(event.issue)}`;
  return event.epic === null ? 'the issue list' : `epic #${String(event.epic)}`;
}

function mergeOverlapEdges(graph, pairs) {
  const issues = runSetIssues(graph.runSet);
  overlapAssertPairs(issues, pairs);
  const cycles = findCycles(issues, graph.edges);
  if (cycles.length > 0) {
    overlapFail(
      `the declared edges hold a cycle among ${cycles.map((c) => c.map(overlapRef).join(', ')).join('; ')}`,
    );
  }
  const unique = overlapDistinct(pairs);
  const entryOf = overlapEntryIndex(graph);
  const crossing = unique.filter((p) => entryOf.get(p.a) !== entryOf.get(p.b));
  if (crossing.length > 0) {
    return {
      kind: 'cross-entry',
      pairs: crossing.map((p) => ({
        ...p,
        epicA: graph.runSet[entryOf.get(p.a) ?? -1]?.epic ?? null,
        epicB: graph.runSet[entryOf.get(p.b) ?? -1]?.epic ?? null,
      })),
    };
  }
  return overlapDirect(graph, unique);
}
function overlapDirect(graph, pairs) {
  const rank = overlapTopoRank(graph);
  const added = [];
  const sequenced = [];
  for (const p of pairs) {
    const ordered =
      transitiveDependents([p.a], graph.edges).includes(p.b) ||
      transitiveDependents([p.b], graph.edges).includes(p.a);
    if (ordered) {
      sequenced.push(p);
      continue;
    }
    const aFirst = (rank.get(p.a) ?? 0) < (rank.get(p.b) ?? 0);
    added.push(aFirst ? { blocker: p.a, dependent: p.b } : { blocker: p.b, dependent: p.a });
  }
  const edges = overlapSortEdges(overlapDistinctEdges([...graph.edges, ...added]));
  return {
    kind: 'ok',
    graph: { runSet: graph.runSet, edges },
    added: overlapSortEdges(added),
    sequenced,
  };
}
function overlapTopoRank(graph) {
  const order = graph.runSet.flatMap((entry) => entry.issues);
  const indegree = new Map(order.map((n) => [n, 0]));
  overlapShiftIndegree(indegree, graph.edges, 1);
  const rank = new Map();
  const nextReady = () => order.find((n) => !rank.has(n) && indegree.get(n) === 0);
  for (let next = nextReady(); next !== undefined; next = nextReady()) {
    rank.set(next, rank.size);
    const ranked = next;
    overlapShiftIndegree(
      indegree,
      graph.edges.filter((e) => e.blocker === ranked),
      -1,
    );
  }
  return rank;
}
function overlapShiftIndegree(indegree, edges, by) {
  for (const e of edges) indegree.set(e.dependent, (indegree.get(e.dependent) ?? 0) + by);
}
function overlapAssertPairs(issues, pairs) {
  for (const p of pairs) {
    const outside = [p.a, p.b].find((n) => !issues.includes(n));
    if (outside !== undefined) {
      overlapFail(
        `pair ${overlapPairLabel(p)} names ${overlapRef(outside)}, which is outside the run set`,
      );
    }
  }
  for (const p of pairs) {
    if (p.a === p.b) overlapFail(`pair ${overlapPairLabel(p)} pairs an issue with itself`);
  }
}
function overlapDistinct(pairs) {
  const seen = new Map();
  for (const p of pairs) {
    const pair = { a: Math.min(p.a, p.b), b: Math.max(p.a, p.b) };
    seen.set(`${String(pair.a)}-${String(pair.b)}`, pair);
  }
  return [...seen.values()].sort((x, y) => x.a - y.a || x.b - y.b);
}
function overlapEntryIndex(graph) {
  const entryOf = new Map();
  graph.runSet.forEach((entry, i) => {
    for (const n of entry.issues) entryOf.set(n, i);
  });
  return entryOf;
}
function overlapDistinctEdges(edges) {
  const seen = new Map();
  for (const e of edges) {
    const key = `${String(e.blocker)}>${String(e.dependent)}`;
    if (!seen.has(key)) seen.set(key, { blocker: e.blocker, dependent: e.dependent });
  }
  return [...seen.values()];
}
function overlapSortEdges(edges) {
  return [...edges].sort((x, y) => x.blocker - y.blocker || x.dependent - y.dependent);
}
function overlapRef(issue) {
  return `#${String(issue)}`;
}
function overlapPairLabel(pair) {
  return `{${overlapRef(pair.a)}, ${overlapRef(pair.b)}}`;
}
function overlapFail(message) {
  throw new Error(`run overlap: ${message}`);
}

async function runPreflight(hooks, args) {
  const checks = await runTool(
    hooks,
    'preflight',
    args.attach === null ? ['.'] : ['.', '--attach', args.attach],
  );
  const gate = await runTool(hooks, 'run-gate', [
    args.selection,
    ...args.numbers.map(String),
    ...(args.exclude ? ['--exclude'] : []),
  ]);
  const live = await runTool(hooks, 'live-runs', ['.']);
  const refusals = [...checkRefusals(checks), ...gateRefusals(gate), ...liveRunRefusals(live)];
  const main = mainSnapshot(checks);
  if (gate?.runSet === undefined) {
    return { refusals, dropped: [], graph: null, main, overlap: null, live };
  }
  const graph = { runSet: gate.runSet, edges: gate.edges ?? [] };
  const scout = await runScout(hooks, graph, live, args.attach);
  const found = { refusals, dropped: gateDrops(gate), graph, main, overlap: null, live };
  return settleOverlap(hooks, settleScout(found, scout, args.exclude));
}
async function settleOverlap(hooks, found) {
  const { graph } = found;
  if (graph === null || runSetIssues(graph.runSet).length < 2) {
    return { ...found, overlap: { added: [], sequenced: [], areaMap: 'read' } };
  }
  const estimate = await AGENT_CALLS.overlapEstimator(hooks, graph);
  if (estimate === null) {
    return withRefusals(found, [
      { kind: 'overlap-estimate-failed', message: 'the overlap estimator returned nothing' },
    ]);
  }
  let merged;
  try {
    merged = mergeOverlapEdges(graph, estimate.pairs);
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return withRefusals(found, [{ kind: 'overlap-estimate-failed', message }]);
  }
  if (merged.kind === 'cross-entry') {
    return withRefusals(
      found,
      merged.pairs.map((p) => crossEpicRefusal(p, estimate.pairs)),
    );
  }
  const overlap = {
    added: merged.added.map((e) => ({ ...e, ...pairWord(e.blocker, e.dependent, estimate.pairs) })),
    sequenced: merged.sequenced,
    areaMap: estimate.areaMap,
  };
  return { ...found, graph: merged.graph, overlap };
}
function withRefusals(found, refusals) {
  return { ...found, refusals: [...found.refusals, ...refusals], overlap: null };
}
function crossEpicRefusal(pair, pairs) {
  const word = pairs.find((p) => samePair(p, pair.a, pair.b));
  const epic = (e) => (e === null ? 'the explicit list' : `epic #${String(e)}`);
  const shared = word === undefined ? '' : `; shared ${word.shared.join(', ')}`;
  return {
    kind: 'overlap-cross-epic',
    issue: pair.a,
    message:
      `#${String(pair.a)} (${epic(pair.epicA)}) and #${String(pair.b)} (${epic(pair.epicB)}) ` +
      `may overlap (${word?.confidence ?? 'unsure'})${shared}: ${word?.reason ?? 'no reason given'}` +
      '; epics in one run must be code-disjoint',
  };
}
function pairWord(a, b, pairs) {
  const word = pairs.find((p) => samePair(p, a, b));
  return { confidence: word?.confidence ?? 'unsure', reason: word?.reason ?? '' };
}
function samePair(p, a, b) {
  return (p.a === a && p.b === b) || (p.a === b && p.b === a);
}
function mainSnapshot(checks) {
  const snapshot = checks?.status === 'ok' ? checks.snapshot : undefined;
  if (typeof checks?.worktree !== 'string' || snapshot === undefined || snapshot === null) {
    return null;
  }
  return { worktree: checks.worktree, snapshot };
}
function dropWithDependents(graph, issues) {
  const inGraph = new Set(runSetIssues(graph.runSet));
  const roots = issues.filter((n) => inGraph.has(n));
  const dependents = transitiveDependents(roots, graph.edges);
  const gone = new Set([...roots, ...dependents]);
  return {
    graph: {
      runSet: graph.runSet
        .map((entry) => ({ epic: entry.epic, issues: entry.issues.filter((n) => !gone.has(n)) }))
        .filter((entry) => entry.issues.length > 0),
      edges: graph.edges.filter((e) => !gone.has(e.blocker) && !gone.has(e.dependent)),
    },
    dependents,
  };
}
function checkRefusals(checks) {
  if (checks?.status === 'ok') return [];
  const problems =
    checks?.status === 'refused' && checks.reason === 'preflight-failed'
      ? (checks.problems ?? [])
      : [];
  if (problems.length > 0) return problems.map((p) => ({ kind: p.check, message: p.message }));
  return [{ kind: 'preflight-error', message: toolError(checks, 'preflight') }];
}
function gateRefusals(gate) {
  if (gate?.verdict === 'ok' && gate.runSet !== undefined && gate.edges !== undefined) return [];
  const failures = gate?.verdict === 'refused' ? (gate.failures ?? []) : [];
  if (failures.length > 0) {
    return failures.map((f) => ({
      kind: f.kind,
      ...('issue' in f ? { issue: f.issue } : {}),
      message: f.message,
    }));
  }
  return [{ kind: 'gate-error', message: toolError(gate, 'run gate') }];
}
function gateDrops(gate) {
  return (gate.excluded ?? []).map((x) => {
    if (x.cause === 'dependent') {
      const blockers = x.blockers.map((b) => `#${String(b)}`).join(', ');
      return { issue: x.issue, cause: 'dependent', message: `blocked by dropped ${blockers}` };
    }
    const failure = (gate.failures ?? []).find((f) => 'issue' in f && f.issue === x.issue);
    return { issue: x.issue, cause: 'gate', message: failure?.message ?? 'failed the run gate' };
  });
}
function liveRunRefusals(live) {
  if (live?.status !== 'ok' || live.runs === undefined) {
    return [{ kind: 'live-runs-failed', message: toolError(live, 'live-runs') }];
  }
  const unknown = live.runs.filter((r) => r.pr.state === 'unknown');
  if (unknown.length === 0) return [];
  const branches = unknown.map((r) => r.branch).join(', ');
  return [{ kind: 'live-runs-failed', message: `pull request state unknown for ${branches}` }];
}
async function runScout(hooks, graph, live, attach) {
  const liveRuns = (live?.runs ?? [])
    .filter((r) => !r.spent && r.branch !== attach)
    .map((r) => ({ branch: r.branch, landed: r.landed }));
  const issues = runSetIssues(graph.runSet);
  return AGENT_CALLS.scout(hooks, {
    issues,
    liveRuns,
    ...(attach === null ? {} : { prHead: `origin/${attach}` }),
  });
}
function settleScout(found, scout, exclude) {
  const issues = runSetIssues(found.graph.runSet);
  const judged = new Set((scout?.issues ?? []).map((v) => v.issue));
  const unjudged = issues.filter((n) => !judged.has(n));
  const refusals = [...found.refusals];
  if (unjudged.length > 0) {
    refusals.push({
      kind: 'scout-unavailable',
      message: `no scout verdict for ${unjudged.map((n) => `#${String(n)}`).join(', ')}`,
    });
  }
  for (const o of scout?.overlaps ?? []) {
    refusals.push({ kind: 'overlap', issue: o.issue, message: `${o.branch}: ${o.evidence}` });
  }
  const stale = (scout?.issues ?? []).filter((v) => v.stale && issues.includes(v.issue));
  if (!exclude) {
    for (const v of stale) refusals.push({ kind: 'stale', issue: v.issue, message: v.evidence });
    return { ...found, refusals };
  }
  const { graph, dependents } = dropWithDependents(
    found.graph,
    stale.map((v) => v.issue),
  );
  if (graph.runSet.length === 0) {
    refusals.push({ kind: 'empty-run-set', message: 'no issue is left after the stale drops' });
  }
  const dropped = [
    ...found.dropped,
    ...stale.map((v) => ({ issue: v.issue, cause: 'stale', message: v.evidence })),
    ...dependents.map((n) => ({
      issue: n,
      cause: 'dependent',
      message: 'blocked by a stale issue',
    })),
  ];
  return { ...found, refusals, dropped, graph };
}
function toolError(out, what) {
  if (out === null) return `the runner returned nothing for ${what}`;
  return (
    out.stderrTail ??
    out.errors?.[0]?.message ??
    out.reason ??
    `${what} exited ${String(out.exitCode)} with no usable verdict`
  );
}

async function cleanupSpent(hooks, live) {
  const report = {
    tornDown: [],
    skipped: [],
    residue: [],
    blocked: null,
    stop: null,
  };
  if (live?.status !== 'ok' || live.runs === undefined) {
    report.blocked = envelopeProblem('live-runs', live);
    return report;
  }
  for (const run of live.runs) {
    await cleanupRun(hooks, run, report);
    if (report.stop !== null) break;
  }
  return report;
}
async function cleanupRun(hooks, run, report) {
  const target = spentTarget(run);
  if (target === null) return;
  if ('why' in target) report.skipped.push(target);
  else await tearDownSpent(hooks, target.path, report);
}
async function tearDownSpent(hooks, path, report) {
  const tag = `spent-${String(report.tornDown.length + report.residue.length + 1)}`;
  const out = await runTool(hooks, 'teardown', [path], { ...PRE_CUT, tag });
  if (out?.status === 'ok') {
    report.tornDown.push(path);
  } else if (out?.status === 'refused' && out.reason === 'source-shrank') {
    report.stop = envelopeProblem('teardown', out);
  } else {
    report.residue.push(`${path}: ${envelopeProblem('teardown', out)}`);
  }
}
function spentTarget(run) {
  if (run.spentUnverified) {
    return { path: run.path, why: 'its PR is over, but the PR head could not be checked' };
  }
  if (!run.spent) return null;
  if (run.dirty !== false) {
    return {
      path: run.path,
      why: run.dirty === true ? 'uncommitted changes' : 'dirtiness unknown',
    };
  }
  if (run.nested.length > 0) {
    return { path: run.path, why: `nested worktrees: ${run.nested.join(', ')}` };
  }
  return { path: run.path };
}

async function runShip(hooks, rawArgs) {
  const parsed = parseShipArgs(rawArgs);
  if (parsed.refusal !== undefined) return refusedReport([parsed.refusal], []);
  hooks.phase(PHASE_TITLES.preflight);
  const pre = await runPreflight(hooks, parsed.args);
  if (pre.refusals.length > 0 || pre.graph === null || pre.overlap === null) {
    return refusedReport(pre.refusals, pre.dropped);
  }
  const { graph, overlap } = pre;
  if (parsed.args.preflightOnly) {
    return { status: 'preflight-ok', dropped: pre.dropped, graph, overlap, epics: [] };
  }
  const cleanup = await cleanupSpent(hooks, pre.live);
  if (cleanup.stop !== null) {
    return {
      ...refusedReport([{ kind: 'source-shrank', message: cleanup.stop }], pre.dropped),
      cleanup,
    };
  }
  hooks.phase(PHASE_TITLES.issues);
  const epics = await runEntries(
    hooks,
    graph,
    { maxSlices: parsed.args.maxSlices, launch: pre.main, overlap },
    parsed.args.attach,
  );
  return { status: 'done', dropped: pre.dropped, overlap, epics, cleanup };
}
async function runEntries(hooks, graph, opts, attach) {
  const cuts = [];
  for (const entry of graph.runSet) cuts.push(await cutEntry(hooks, entry, attach));
  const lost = cuts.flatMap((c) => ('stopped' in c ? c.issues : []));
  const kept = dropWithDependents(graph, lost).graph;
  const setups = kept.runSet.flatMap((entry) => {
    const cut = cuts.find((c) => 'setup' in c && c.setup.epic === entry.epic);
    return cut !== undefined && 'setup' in cut ? [cut.setup] : [];
  });
  const driven =
    setups.length === 0 ? [] : await drive({ hooks, graph: kept, entries: setups, ...opts });
  return cuts.map((c, k) => {
    if ('stopped' in c) {
      return {
        ...c.stopped,
        schedule: c.issues.map((n) => neverStarted(n, graph, opts.overlap)),
      };
    }
    return cutReport(c.setup, graph, k, driven, opts.overlap);
  });
}
async function cutEntry(hooks, entry, attach) {
  const tag = entry.epic === null ? 'list' : `epic-${String(entry.epic)}`;
  const argv = ['.', ...cutSelection(entry, attach)];
  const cut = await runTool(hooks, 'cut-batch', argv, { ...PRE_CUT, tag });
  const { worktree, branch, base, batch, reportDir } = cut ?? {};
  if (
    cut?.status !== 'ok' ||
    !isText(worktree) ||
    !isText(branch) ||
    !isText(base) ||
    !isText(batch) ||
    !isText(reportDir)
  ) {
    return stoppedEntry(entry, branch ?? '', envelopeProblem('cut-batch', cut));
  }
  const attachedRun = cut.attach?.run ?? null;
  if (attach !== null && attachedRun === null) {
    return stoppedEntry(entry, branch, 'cut-batch --attach named no attached run');
  }
  const found = await batchRegistry(hooks, cut.attach ?? null, { batch, reportDir, tag });
  if ('stop' in found) return stoppedEntry(entry, branch, found.stop);
  const { registry } = found;
  return {
    setup: {
      epic: entry.epic,
      tag,
      branch,
      main: worktree,
      batch,
      base,
      reportDir,
      registry,
      attachedRun,
    },
  };
}
function cutSelection(entry, attach) {
  if (attach !== null) return ['--attach', attach, '--attached-run'];
  return entry.epic === null
    ? ['--issues', entry.issues.join(',')]
    : ['--epic', String(entry.epic)];
}
async function batchRegistry(hooks, attached, at) {
  if (attached !== null && !attached.created) {
    return attached.registry === null
      ? { stop: 'cut-batch --attach found no trimmed pool registry for the reused batch' }
      : { registry: attached.registry };
  }
  const argv = [at.batch, '--report-dir', at.reportDir];
  const prov = await runTool(hooks, 'provision-batch', argv, runPlace(at.reportDir, at.tag));
  if (prov?.status !== 'ok' || !isText(prov.registry)) {
    return { stop: envelopeProblem('provision-batch', prov) };
  }
  return { registry: prov.registry };
}
function isText(value) {
  return typeof value === 'string';
}
function stoppedEntry(entry, branch, message) {
  const stopped = {
    epic: entry.epic,
    branch,
    outcome: 'stopped',
    message,
    issues: entry.issues.map((issue) => ({
      issue,
      outcome: 'blocked',
      cite: 'see',
      reason: 'its batch was not set up',
    })),
    schedule: [],
    residue: [],
  };
  return { stopped, issues: entry.issues };
}
function cutReport(setup, graph, k, driven, overlap) {
  const report = driven.find((r) => r.epic === setup.epic) ?? {
    epic: setup.epic,
    branch: setup.branch,
    outcome: 'nothing-landed',
    issues: [],
    schedule: [],
    residue: [],
  };
  const planned = graph.runSet[k]?.issues ?? [];
  const issues = planned.map(
    (issue) =>
      report.issues.find((r) => r.issue === issue) ?? {
        issue,
        outcome: 'skipped',
        cite: 'see',
        reason: 'a blocker lost its batch',
      },
  );
  const schedule = planned.map(
    (issue) =>
      report.schedule.find((s) => s.issue === issue) ?? neverStarted(issue, graph, overlap),
  );
  return { ...report, issues, schedule };
}
function refusedReport(refusals, dropped) {
  return { status: 'refused', refusals, dropped, epics: [] };
}

