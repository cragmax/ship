async function syncMasterStep(hooks, ctx) {
  const start = await runTool(hooks, 'sync-master', [ctx.batch], runPlace(ctx.reportDir, ctx.tag));
  if (start?.status === 'conflict' && start.outcome === 'needs-resolution') {
    return resolveAndContinue(hooks, ctx, start.pending ?? []);
  }
  return syncVerdict(start, 'merged');
}
async function resolveAndContinue(hooks, ctx, pending) {
  if (pending.length === 0) {
    return syncFailure(
      `sync-master needs resolution but named no path; merge left in ${ctx.batch}`,
    );
  }
  const values = { batch: ctx.batch, pending, reportPath: `${ctx.reportDir}/resolve.md` };
  const answer = await AGENT_CALLS.resolver(hooks, values, ctx.tag);
  if (answer?.verdict !== 'resolved') {
    const said = answer === null ? 'returned nothing' : `said ${answer.summary}`;
    return syncFailure(`the resolver ${said}; merge left in progress in ${ctx.batch}`);
  }
  const done = await runTool(
    hooks,
    'sync-master',
    [ctx.batch, '--continue'],
    runPlace(ctx.reportDir, `${ctx.tag}-continue`),
  );
  return syncVerdict(done, 'resolved');
}
function syncVerdict(out, merged) {
  if (out?.status === 'ok' && out.outcome === 'up-to-date') {
    return { verdict: 'up-to-date', commit: null, message: 'origin/master already merged' };
  }
  if (out?.status === 'ok' && out.outcome === 'merged' && typeof out.commit === 'string') {
    return {
      verdict: merged,
      commit: out.commit,
      message: `merged origin/master as ${out.commit}`,
    };
  }
  const message = envelopeProblem('sync-master', out);
  if (out?.status === 'refused' && out.reason === 'code-conflict') {
    return { verdict: 'code-conflict', commit: null, message };
  }
  return syncFailure(message);
}
function syncFailure(message) {
  return { verdict: 'failed', commit: null, message };
}

async function epicEnd(input) {
  const { hooks, entry } = input;
  const serverTier = [await tierRun(input, 'paper'), await tierRun(input, 'folia')];
  const sync = await syncMasterStep(hooks, entry);
  const published =
    sync.verdict === 'code-conflict' || sync.verdict === 'failed'
      ? { outcome: 'stopped', message: `master sync ${sync.verdict}: ${sync.message}` }
      : await bumpAndPublish(input, serverTier, sync);
  return {
    epic: entry.epic,
    branch: entry.branch,
    ...published,
    issues: input.issues,
    mainUntouched: await mainUntouched(input),
    residue: input.residue,
  };
}
async function tierRun(input, engine) {
  const { entry } = input;
  const argv = [
    entry.batch,
    '--engine',
    engine,
    '--registry',
    entry.registry,
    '--log',
    `${entry.reportDir}/server-tier-${engine}.log`,
  ];
  const out = await runTool(input.hooks, 'server-tier', argv, runPlace(entry.reportDir, engine));
  return { engine, out };
}
async function bumpAndPublish(input, serverTier, sync) {
  const { hooks, entry } = input;
  const bump = await runTool(hooks, 'bump', [entry.batch], runPlace(entry.reportDir, entry.tag));
  if (bump?.status !== 'ok') return { outcome: 'stopped', message: envelopeProblem('bump', bump) };
  const body = renderPrBody({
    epic: entry.epic,
    branch: entry.branch,
    reportDir: entry.reportDir,
    landed: input.landed,
    unlanded: input.issues.filter((i) => i.outcome !== 'landed'),
    serverTier,
    sync,
    bump,
  });
  const bodyPath = `${entry.reportDir}/pr-body.md`;
  const argv = [
    entry.batch,
    '--title',
    prTitle({ branch: entry.branch, landed: input.landed }),
    '--body-file',
    bodyPath,
    '--log',
    `${entry.reportDir}/publish.log`,
  ];
  const place = runPlace(entry.reportDir, entry.tag, { path: bodyPath, content: body });
  const out = await runTool(hooks, 'publish', argv, place);
  const pr = out?.status === 'ok' ? out.pr : null;
  if (pr === undefined || pr === null) {
    return { outcome: 'stopped', message: envelopeProblem('publish', out) };
  }
  return { outcome: 'pr', pr: pr.number };
}
async function mainUntouched(input) {
  const { entry, launch } = input;
  const out = await runTool(
    input.hooks,
    'preflight',
    [entry.main],
    runPlace(entry.reportDir, entry.tag),
  );
  const now = out?.snapshot;
  if (launch === null || now === undefined || now === null) return null;
  return now.head === launch.snapshot.head && now.dirty === launch.snapshot.dirty;
}

async function runAttempt(ctx, issue, attempt) {
  const at = newAttempt(ctx, issue, attempt);
  const stop = await authorSlice(at).catch((err) => stageThrew(at, err));
  if (stop !== null) return endAttempt(at, stop);
  const landing = ctx.queue
    .enqueue(() => landSlice(at).catch((err) => landThrew(at, err)))
    .then((event) => endAttempt(at, event));
  return { kind: 'authored', issue, landing };
}
function newAttempt(ctx, issue, attempt) {
  const tag = `${String(issue)}-${String(attempt)}`;
  return {
    ctx,
    issue,
    attempt,
    tag,
    place: runPlace(ctx.reportDir, tag),
    slice: null,
    base: '',
    projectDir: '',
    sha: '',
    card: null,
    tdd: null,
    review: null,
    testReview: null,
    work: null,
    commit: null,
  };
}
const AUTHOR_STAGES = [
  recheckStage,
  cutStage,
  provisionStage,
  planStage,
  planReviewStage,
  tddStage,
  reviewStage,
  testReviewStage,
];
async function authorSlice(at) {
  for (const stage of AUTHOR_STAGES) {
    if (at.ctx.isHalting()) return haltedStop(at);
    const stop = await stage(at);
    if (stop !== null) return stop;
  }
  const { card, tdd, review, testReview } = at;
  if (card === null || tdd === null || review === null)
    return blocked(at, 'authoring left no work');
  at.work = { card, tdd, review, testReview };
  return null;
}
async function recheckStage(at) {
  const out = await runTool(at.ctx.hooks, 'check', [String(at.issue)], at.place);
  if (out === null) return died(at);
  if (out.ready === true) return null;
  if (out.ready === false) return { kind: 'label-removed', issue: at.issue };
  return blocked(at, `check gave no verdict: ${out.stderrTail ?? `exit ${String(out.exitCode)}`}`);
}
async function cutStage(at) {
  const argv = [at.ctx.batch, '--issue', String(at.issue), '--attempt', String(at.attempt)];
  const out = await runTool(at.ctx.hooks, 'cut-slice', argv, at.place);
  if (typeof out?.slice === 'string') at.slice = out.slice;
  if (out === null) return died(at);
  if (out.status !== 'ok' || at.slice === null || typeof out.base !== 'string') {
    return blocked(at, envelopeProblem('cut-slice', out));
  }
  at.base = out.base;
  return null;
}
async function provisionStage(at) {
  const argv = [at.slice ?? '', '--batch', at.ctx.batch, '--server'];
  const out = await runTool(at.ctx.hooks, 'provision', argv, at.place);
  if (out === null) return died(at);
  const projectDir = out.env?.PH_PROJECT_DIR;
  if (out.status !== 'ok' || typeof projectDir !== 'string') {
    return blocked(at, envelopeProblem('provision', out));
  }
  at.projectDir = projectDir;
  return null;
}
async function planStage(at) {
  const card = await AGENT_CALLS.planner(at.ctx.hooks, plannerValues(at, 'plan'), at.tag);
  return acceptCard(at, card);
}
async function planReviewStage(at) {
  const values = {
    issue: at.issue,
    slice: at.slice ?? '',
    planPath: planPath(at),
    findingsPath: `${at.ctx.reportDir}/plan-review-${at.tag}.md`,
  };
  const review = await AGENT_CALLS.planReviewer(at.ctx.hooks, values, at.tag);
  if (review === null) return died(at);
  if (review.findings === 0) return null;
  const applied = await AGENT_CALLS.planner(
    at.ctx.hooks,
    plannerValues(at, 'apply', review.findingsPath),
    at.tag,
  );
  return acceptCard(at, applied);
}
async function tddStage(at) {
  const card = requireCard(at);
  const values = {
    issue: at.issue,
    attempt: at.attempt,
    slice: at.slice ?? '',
    base: at.base,
    planPath: planPath(at),
    reportPath: `${at.ctx.reportDir}/tdd-${at.tag}.md`,
    messagePath: messagePath(at),
    message: commitMessage(at.issue, card),
    lease: { main: at.ctx.main, projectDir: at.projectDir, registry: at.ctx.registry },
  };
  const tdd = await AGENT_CALLS.tdd(at.ctx.hooks, values, at.tag);
  if (tdd === null) return died(at);
  if (tdd.verdict === 'BLOCKED' || tdd.sha === '') {
    return blocked(at, `tdd ${tdd.verdict}: ${tdd.reason ?? 'no commit'}`);
  }
  at.tdd = tdd;
  at.sha = tdd.sha;
  return null;
}
async function reviewStage(at) {
  const review = await AGENT_CALLS.reviewer(at.ctx.hooks, sliceReviewValues(at, 'review'), at.tag);
  if (review === null) return died(at);
  if (review.verdict === 'blocked') return blocked(at, `review: ${review.summary}`);
  at.review = review;
  at.sha = review.sha;
  return null;
}
async function testReviewStage(at) {
  if (isTrivialSurface(at.tdd?.files ?? [])) return null;
  const values = sliceReviewValues(at, 'test-review');
  const out = await AGENT_CALLS.testReview(at.ctx.hooks, values, at.tag);
  if (out === null) return died(at);
  if (out.verdict === 'blocked') return blocked(at, `test review: ${out.summary}`);
  at.testReview = out;
  at.sha = out.sha;
  return null;
}
async function landSlice(at) {
  if (at.ctx.isHalting()) return haltedStop(at);
  const argv = [
    at.ctx.batch,
    at.sha,
    '--base',
    at.base,
    '--message-file',
    messagePath(at),
    '--log',
    `${at.ctx.reportDir}/land-${at.tag}.log`,
  ];
  const out = await runTool(at.ctx.hooks, 'land', argv, at.place);
  const event = landingEvent(out, { issue: at.issue, epic: at.ctx.epic });
  if (event.kind === 'epic-halt') at.ctx.markHalting();
  if (event.kind === 'committed') at.commit = out?.commit ?? null;
  return event;
}
function landThrew(at, err) {
  at.ctx.markHalting();
  return { kind: 'epic-halt', epic: at.ctx.epic, reason: `land threw: ${errorText(err)}` };
}
async function endAttempt(at, primary) {
  const teardown =
    at.slice === null
      ? null
      : await runTool(at.ctx.hooks, 'teardown', [at.slice], at.place).catch(() => null);
  if (teardownEvent(teardown, at.ctx.epic) !== null) at.ctx.markHalting();
  const ending = {
    primary,
    teardown,
    residue: at.slice === null ? null : teardownResidue(teardown),
    work: at.work,
    commit: at.commit,
  };
  return { kind: 'ended', issue: at.issue, ending };
}
function acceptCard(at, card) {
  if (card === null) return died(at);
  if (card.verdict !== 'plan') return blocked(at, `planner ${card.verdict}: ${card.evidence}`);
  at.card = card;
  return null;
}
function plannerValues(at, mode, findingsPath) {
  return {
    mode,
    issue: at.issue,
    attempt: at.attempt,
    slice: at.slice ?? '',
    reportDir: at.ctx.reportDir,
    planPath: planPath(at),
    ...(findingsPath === undefined ? {} : { findingsPath }),
    priorSlices: at.ctx.priorSlices(),
  };
}
function sliceReviewValues(at, report) {
  return {
    issue: at.issue,
    slice: at.slice ?? '',
    planPath: planPath(at),
    sha: at.sha,
    files: at.tdd?.files ?? [],
    reportPath: `${at.ctx.reportDir}/${report}-${at.tag}.md`,
  };
}
function planPath(at) {
  return `${at.ctx.reportDir}/plans/${String(at.issue)}.md`;
}
function messagePath(at) {
  return `${at.ctx.reportDir}/commit-${at.tag}.txt`;
}
function requireCard(at) {
  if (at.card === null) throw new Error('ship: the tdd stage ran without a plan card');
  return at.card;
}
function haltedStop(at) {
  return { kind: 'epic-halt', epic: at.ctx.epic, reason: 'its epic halted' };
}
function died(at) {
  return { kind: 'agent-died', issue: at.issue };
}
function blocked(at, reason) {
  return { kind: 'blocked', issue: at.issue, reason };
}
function stageThrew(at, err) {
  return blocked(at, `a stage threw: ${errorText(err)}`);
}
function errorText(err) {
  return err instanceof Error ? err.message : String(err);
}

async function drive(input) {
  const d = newDrive(input);
  apply(d, createScheduler({ ...input.graph, maxSlices: input.maxSlices }));
  while (d.flights.size > 0) {
    const note = await Promise.race(d.flights.values());
    d.flights.delete(flightKey(note));
    onNote(d, note);
  }
  return input.entries.map((_entry, i) => entryReport(d, i));
}
function newDrive(input) {
  const d = {
    input,
    contexts: [],
    scheduler: null,
    flights: new Map(),
    attempts: new Map(),
    halting: new Set(),
    halted: new Set(),
    outcomes: new Map(),
    landed: new Map(),
    residue: new Map(),
    ends: new Map(),
    epicEndEntered: false,
  };
  input.entries.forEach((entry, i) => {
    d.contexts.push({
      ...entry,
      hooks: input.hooks,
      queue: createCommitQueue(),
      isHalting: () => d.halting.has(i),
      markHalting: () => {
        d.halting.add(i);
      },
      priorSlices: () =>
        (d.landed.get(i) ?? []).map((l) => ({
          issue: l.issue,
          commit: l.commit,
          plan: l.card.planPath,
        })),
    });
  });
  return d;
}
function flightKey(note) {
  return note.kind === 'epic-end' ? `epic:${String(note.entry)}` : `issue:${String(note.issue)}`;
}
function onNote(d, note) {
  if (note.kind === 'epic-end') {
    d.ends.set(note.entry, note.report);
  } else if (note.kind === 'authored') {
    d.flights.set(flightKey(note), note.landing);
    feed(d, [{ kind: 'slot-free', issue: note.issue }]);
  } else {
    settle(d, note.issue, note.ending);
  }
}
function settle(d, issue, ending) {
  const i = entryOfIssue(d, issue);
  const epic = d.input.entries[i]?.epic ?? null;
  const events = settleEvents(ending.primary, ending.teardown, {
    issue,
    epic,
    entryHalted: d.halted.has(i),
  });
  if (ending.residue !== null) d.residue.set(i, [...(d.residue.get(i) ?? []), ending.residue]);
  if (events.some((e) => e.kind === 'epic-halt')) {
    d.halting.add(i);
    d.halted.add(i);
  }
  record(d, i, issue, ending, events);
  feed(d, events);
}
function record(d, i, issue, ending, events) {
  const { work, commit } = ending;
  if (events.some((e) => e.kind === 'committed') && work !== null && commit !== null) {
    d.landed.set(i, [...(d.landed.get(i) ?? []), { ...work, issue, commit }]);
    d.outcomes.set(issue, { issue, outcome: 'landed', cite: work.card.closes, commit });
    return;
  }
  const report = unlandedOutcome(issue, ending, d.halted.has(i));
  if (report !== null) d.outcomes.set(issue, report);
}
function unlandedOutcome(issue, ending, halted) {
  const { primary, commit } = ending;
  const reason = 'reason' in primary ? primary.reason : undefined;
  if (primary.kind === 'committed' && commit !== null) {
    return { issue, outcome: 'landed-then-halted', cite: 'see', commit };
  }
  if (halted)
    return { issue, outcome: 'halted', cite: 'see', ...(reason === undefined ? {} : { reason }) };
  if (primary.kind === 'blocked')
    return { issue, outcome: 'blocked', cite: 'see', reason: primary.reason };
  if (primary.kind === 'label-removed') {
    return { issue, outcome: 'removed', cite: 'see', reason: 'no longer open and ready-for-agent' };
  }
  return null;
}
function feed(d, events) {
  for (const event of events) {
    d.input.hooks.log(`fed ${event.kind} ${eventSubject(event)}`);
    if (d.scheduler === null) throw new Error('ship: fed an event before the scheduler started');
    apply(d, advance(d.scheduler, event));
  }
}
function apply(d, t) {
  d.scheduler = t.state;
  for (const action of t.actions) act(d, action);
}
function act(d, action) {
  switch (action.kind) {
    case 'start': {
      const ctx = d.contexts[entryOfIssue(d, action.issue)];
      if (ctx === undefined) throw new Error(`ship: no entry holds #${String(action.issue)}`);
      const attempt = d.attempts.get(action.issue) ?? 1;
      d.flights.set(`issue:${String(action.issue)}`, runAttempt(ctx, action.issue, attempt));
      break;
    }
    case 'requeue':
    case 'retry':
      d.attempts.set(action.issue, (d.attempts.get(action.issue) ?? 1) + 1);
      break;
    case 'skip':
      d.outcomes.set(action.issue, {
        issue: action.issue,
        outcome: 'skipped',
        cite: 'see',
        reason: `blocker #${String(action.cause.root)} ${action.cause.trigger}`,
      });
      break;
    case 'block':
      d.outcomes.set(action.issue, {
        issue: action.issue,
        outcome: 'blocked',
        cite: 'see',
        reason: 'its agent died on the retry too',
      });
      break;
    case 'epic-done':
      endEpic(d, entryOfEpic(d, action.epic));
      break;
    case 'epic-halted':
      d.ends.set(entryOfEpic(d, action.epic), 'halted');
      break;
  }
}
function endEpic(d, i) {
  const landed = d.landed.get(i) ?? [];
  const entry = d.input.entries[i];
  if (landed.length === 0 || entry === undefined) {
    d.ends.set(i, 'nothing-landed');
    return;
  }
  if (!d.epicEndEntered) d.input.hooks.phase(PHASE_TITLES.epicEnd);
  d.epicEndEntered = true;
  const issues = issueReports(d, i);
  const residue = d.residue.get(i) ?? [];
  const report = epicEnd({
    hooks: d.input.hooks,
    entry,
    landed,
    issues,
    residue,
    launch: d.input.launch,
  }).catch((err) => ({
    epic: entry.epic,
    branch: entry.branch,
    outcome: 'stopped',
    message: `the epic end threw: ${err instanceof Error ? err.message : String(err)}`,
    issues,
    residue,
  }));
  d.flights.set(
    `epic:${String(i)}`,
    report.then((r) => ({ kind: 'epic-end', entry: i, report: r })),
  );
}
function entryReport(d, i) {
  const end = d.ends.get(i) ?? 'halted';
  if (typeof end !== 'string') return end;
  const entry = d.input.entries[i];
  return {
    epic: entry?.epic ?? null,
    branch: entry?.branch ?? '',
    outcome: end,
    issues: issueReports(d, i),
    residue: d.residue.get(i) ?? [],
  };
}
function issueReports(d, i) {
  const issues = d.input.graph.runSet[i]?.issues ?? [];
  return issues.map((issue) => d.outcomes.get(issue) ?? { issue, outcome: 'halted', cite: 'see' });
}
function entryOfIssue(d, issue) {
  return d.input.graph.runSet.findIndex((entry) => entry.issues.includes(issue));
}
function entryOfEpic(d, epic) {
  return d.input.graph.runSet.findIndex((entry) => entry.epic === epic);
}
function eventSubject(event) {
  if (event.kind !== 'epic-halt') return `#${String(event.issue)}`;
  return event.epic === null ? 'the issue list' : `epic #${String(event.epic)}`;
}

async function runPreflight(hooks, args) {
  const checks = await runTool(hooks, 'preflight', ['.']);
  const gate = await runTool(hooks, 'run-gate', [
    args.selection,
    ...args.numbers.map(String),
    ...(args.exclude ? ['--exclude'] : []),
  ]);
  const live = await runTool(hooks, 'live-runs', ['.']);
  const refusals = [...checkRefusals(checks), ...gateRefusals(gate), ...liveRunRefusals(live)];
  const main = mainSnapshot(checks);
  if (gate?.runSet === undefined) return { refusals, dropped: [], graph: null, main };
  const graph = { runSet: gate.runSet, edges: gate.edges ?? [] };
  const scout = await runScout(hooks, graph, live);
  return settleScout({ refusals, dropped: gateDrops(gate), graph, main }, scout, args.exclude);
}
function mainSnapshot(checks) {
  const snapshot = checks?.status === 'ok' ? checks.snapshot : undefined;
  if (typeof checks?.worktree !== 'string' || snapshot === undefined || snapshot === null) {
    return null;
  }
  return { worktree: checks.worktree, snapshot };
}
function dropWithDependents(graph, issues) {
  const inGraph = new Set(runSetIssues(graph.runSet));
  const roots = issues.filter((n) => inGraph.has(n));
  const dependents = transitiveDependents(roots, graph.edges);
  const gone = new Set([...roots, ...dependents]);
  return {
    graph: {
      runSet: graph.runSet
        .map((entry) => ({ epic: entry.epic, issues: entry.issues.filter((n) => !gone.has(n)) }))
        .filter((entry) => entry.issues.length > 0),
      edges: graph.edges.filter((e) => !gone.has(e.blocker) && !gone.has(e.dependent)),
    },
    dependents,
  };
}
function checkRefusals(checks) {
  if (checks?.status === 'ok') return [];
  const problems =
    checks?.status === 'refused' && checks.reason === 'preflight-failed'
      ? (checks.problems ?? [])
      : [];
  if (problems.length > 0) return problems.map((p) => ({ kind: p.check, message: p.message }));
  return [{ kind: 'preflight-error', message: toolError(checks, 'preflight') }];
}
function gateRefusals(gate) {
  if (gate?.verdict === 'ok' && gate.runSet !== undefined && gate.edges !== undefined) return [];
  const failures = gate?.verdict === 'refused' ? (gate.failures ?? []) : [];
  if (failures.length > 0) {
    return failures.map((f) => ({
      kind: f.kind,
      ...('issue' in f ? { issue: f.issue } : {}),
      message: f.message,
    }));
  }
  return [{ kind: 'gate-error', message: toolError(gate, 'run gate') }];
}
function gateDrops(gate) {
  return (gate.excluded ?? []).map((x) => {
    if (x.cause === 'dependent') {
      const blockers = x.blockers.map((b) => `#${String(b)}`).join(', ');
      return { issue: x.issue, cause: 'dependent', message: `blocked by dropped ${blockers}` };
    }
    const failure = (gate.failures ?? []).find((f) => 'issue' in f && f.issue === x.issue);
    return { issue: x.issue, cause: 'gate', message: failure?.message ?? 'failed the run gate' };
  });
}
function liveRunRefusals(live) {
  if (live?.status !== 'ok' || live.runs === undefined) {
    return [{ kind: 'live-runs-failed', message: toolError(live, 'live-runs') }];
  }
  const unknown = live.runs.filter((r) => r.pr.state === 'unknown');
  if (unknown.length === 0) return [];
  const branches = unknown.map((r) => r.branch).join(', ');
  return [{ kind: 'live-runs-failed', message: `pull request state unknown for ${branches}` }];
}
async function runScout(hooks, graph, live) {
  const liveRuns = (live?.runs ?? [])
    .filter((r) => !r.spent)
    .map((r) => ({ branch: r.branch, landed: r.landed }));
  return AGENT_CALLS.scout(hooks, { issues: runSetIssues(graph.runSet), liveRuns });
}
function settleScout(found, scout, exclude) {
  const issues = runSetIssues(found.graph.runSet);
  const judged = new Set((scout?.issues ?? []).map((v) => v.issue));
  const unjudged = issues.filter((n) => !judged.has(n));
  const refusals = [...found.refusals];
  if (unjudged.length > 0) {
    refusals.push({
      kind: 'scout-unavailable',
      message: `no scout verdict for ${unjudged.map((n) => `#${String(n)}`).join(', ')}`,
    });
  }
  for (const o of scout?.overlaps ?? []) {
    refusals.push({ kind: 'overlap', issue: o.issue, message: `${o.branch}: ${o.evidence}` });
  }
  const stale = (scout?.issues ?? []).filter((v) => v.stale && issues.includes(v.issue));
  if (!exclude) {
    for (const v of stale) refusals.push({ kind: 'stale', issue: v.issue, message: v.evidence });
    return { refusals, dropped: found.dropped, graph: found.graph, main: found.main };
  }
  const { graph, dependents } = dropWithDependents(
    found.graph,
    stale.map((v) => v.issue),
  );
  if (graph.runSet.length === 0) {
    refusals.push({ kind: 'empty-run-set', message: 'no issue is left after the stale drops' });
  }
  const dropped = [
    ...found.dropped,
    ...stale.map((v) => ({ issue: v.issue, cause: 'stale', message: v.evidence })),
    ...dependents.map((n) => ({
      issue: n,
      cause: 'dependent',
      message: 'blocked by a stale issue',
    })),
  ];
  return { refusals, dropped, graph, main: found.main };
}
function toolError(out, what) {
  if (out === null) return `the runner returned nothing for ${what}`;
  return (
    out.stderrTail ??
    out.errors?.[0]?.message ??
    out.reason ??
    `${what} exited ${String(out.exitCode)} with no usable verdict`
  );
}

async function runShip(hooks, rawArgs) {
  const parsed = parseShipArgs(rawArgs);
  if (parsed.refusal !== undefined) return refusedReport([parsed.refusal], []);
  hooks.phase(PHASE_TITLES.preflight);
  const pre = await runPreflight(hooks, parsed.args);
  if (pre.refusals.length > 0 || pre.graph === null) {
    return refusedReport(pre.refusals, pre.dropped);
  }
  if (parsed.args.preflightOnly) {
    return { status: 'preflight-ok', dropped: pre.dropped, graph: pre.graph, epics: [] };
  }
  hooks.phase(PHASE_TITLES.issues);
  const epics = await runEntries(hooks, pre.graph, {
    maxSlices: parsed.args.maxSlices,
    launch: pre.main,
  });
  return { status: 'done', dropped: pre.dropped, epics };
}
async function runEntries(hooks, graph, opts) {
  const cuts = [];
  for (const entry of graph.runSet) cuts.push(await cutEntry(hooks, entry));
  const lost = cuts.flatMap((c) => ('stopped' in c ? c.issues : []));
  const kept = dropWithDependents(graph, lost).graph;
  const setups = kept.runSet.flatMap((entry) => {
    const cut = cuts.find((c) => 'setup' in c && c.setup.epic === entry.epic);
    return cut !== undefined && 'setup' in cut ? [cut.setup] : [];
  });
  const driven =
    setups.length === 0 ? [] : await drive({ hooks, graph: kept, entries: setups, ...opts });
  return cuts.map((c, k) =>
    'stopped' in c ? c.stopped : cutReport(c.setup, graph.runSet[k], driven),
  );
}
async function cutEntry(hooks, entry) {
  const tag = entry.epic === null ? 'list' : `epic-${String(entry.epic)}`;
  const selection =
    entry.epic === null ? ['--issues', entry.issues.join(',')] : ['--epic', String(entry.epic)];
  const cut = await runTool(hooks, 'cut-batch', ['.', ...selection], { ...PRE_CUT, tag });
  const { worktree, branch, batch, reportDir } = cut ?? {};
  if (
    cut?.status !== 'ok' ||
    !isText(worktree) ||
    !isText(branch) ||
    !isText(batch) ||
    !isText(reportDir)
  ) {
    return stoppedEntry(entry, branch ?? '', envelopeProblem('cut-batch', cut));
  }
  const argv = [batch, '--report-dir', reportDir];
  const prov = await runTool(hooks, 'provision-batch', argv, runPlace(reportDir, tag));
  if (prov?.status !== 'ok' || !isText(prov.registry)) {
    return stoppedEntry(entry, branch, envelopeProblem('provision-batch', prov));
  }
  const registry = prov.registry;
  return { setup: { epic: entry.epic, tag, branch, main: worktree, batch, reportDir, registry } };
}
function isText(value) {
  return typeof value === 'string';
}
function stoppedEntry(entry, branch, message) {
  const stopped = {
    epic: entry.epic,
    branch,
    outcome: 'stopped',
    message,
    issues: entry.issues.map((issue) => ({
      issue,
      outcome: 'blocked',
      cite: 'see',
      reason: 'its batch was not set up',
    })),
    residue: [],
  };
  return { stopped, issues: entry.issues };
}
function cutReport(setup, entry, driven) {
  const report = driven.find((r) => r.epic === setup.epic) ?? {
    epic: setup.epic,
    branch: setup.branch,
    outcome: 'nothing-landed',
    issues: [],
    residue: [],
  };
  const issues = (entry?.issues ?? []).map(
    (issue) =>
      report.issues.find((r) => r.issue === issue) ?? {
        issue,
        outcome: 'skipped',
        cite: 'see',
        reason: 'a blocker lost its batch',
      },
  );
  return { ...report, issues };
}
function refusedReport(refusals, dropped) {
  return { status: 'refused', refusals, dropped, epics: [] };
}

return await runShip({ agent, parallel, pipeline, phase, log }, args);
