const ARG_KEYS = ['epics', 'issues', 'exclude', 'preflightOnly', 'maxSlices'];
class ArgsError extends Error {}
function parseShipArgs(raw) {
  try {
    return { args: typeof raw === 'string' ? parseText(raw) : parseObject(raw) };
  } catch (err) {
    if (!(err instanceof ArgsError)) throw err;
    return {
      refusal: {
        kind: 'usage',
        message: `${err.message}; expected epics|issues N... [--exclude] [--preflight-only] [--max-slices K]`,
      },
    };
  }
}
function parseText(text) {
  const trimmed = text.trim();
  if (trimmed.startsWith('{')) return parseObject(parseJson(trimmed));
  const [first, ...rest] = trimmed.split(/\s+/);
  return validated({ selection: selectionWord(first), ...parseTokens(rest) });
}
function selectionWord(word) {
  if (word === 'epics' || word === 'issues') return word;
  throw new ArgsError(
    word === undefined || word === ''
      ? 'no arguments'
      : `'${word}' is not epics or issues (bare numbers are ambiguous)`,
  );
}
function parseTokens(tokens) {
  const numbers = [];
  const args = { numbers, exclude: false, preflightOnly: false, maxSlices: MAX_SLICES };
  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i] ?? '';
    switch (token) {
      case '--exclude':
        args.exclude = true;
        break;
      case '--preflight-only':
        args.preflightOnly = true;
        break;
      case '--max-slices':
        args.maxSlices = positiveInteger(tokens[++i], '--max-slices');
        break;
      default:
        numbers.push(...numberList(token));
    }
  }
  return args;
}
function parseObject(raw) {
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) {
    throw new ArgsError(raw === undefined || raw === null ? 'no arguments' : 'not an object');
  }
  const record = raw;
  const unknownKey = Object.keys(record).find((key) => !ARG_KEYS.includes(key));
  if (unknownKey !== undefined) throw new ArgsError(`unknown key '${unknownKey}'`);
  const hasEpics = Object.hasOwn(record, 'epics');
  if (hasEpics === Object.hasOwn(record, 'issues')) {
    throw new ArgsError('give exactly one of epics and issues');
  }
  const selection = hasEpics ? 'epics' : 'issues';
  const list = record[selection];
  if (!Array.isArray(list)) throw new ArgsError(`${selection} is not a list`);
  return validated({
    selection,
    numbers: list.map((n) => positiveInteger(n, selection)),
    exclude: flag(record, 'exclude'),
    preflightOnly: flag(record, 'preflightOnly'),
    maxSlices:
      record['maxSlices'] === undefined
        ? MAX_SLICES
        : positiveInteger(record['maxSlices'], 'maxSlices'),
  });
}
function parseJson(text) {
  try {
    return JSON.parse(text);
  } catch {
    throw new ArgsError('not valid JSON');
  }
}
function numberList(token) {
  if (token.startsWith('--')) throw new ArgsError(`unknown flag '${token}'`);
  return token
    .split(',')
    .filter((piece) => piece !== '')
    .map((piece) => positiveInteger(piece.replace(/^#/, ''), piece));
}
function positiveInteger(value, what) {
  const n = typeof value === 'string' && /^\d+$/.test(value) ? Number(value) : value;
  if (typeof n !== 'number' || !Number.isInteger(n) || n < 1) {
    throw new ArgsError(`${what}: '${String(value)}' is not a positive integer`);
  }
  return n;
}
function flag(record, key) {
  const value = record[key];
  if (value === undefined) return false;
  if (typeof value !== 'boolean') throw new ArgsError(`${key} is not a boolean`);
  return value;
}
function validated(args) {
  if (args.numbers.length === 0) throw new ArgsError(`no ${args.selection} numbers`);
  const twice = args.numbers.find((n, i) => args.numbers.indexOf(n) !== i);
  if (twice !== undefined) throw new ArgsError(`#${String(twice)} is given twice`);
  return args;
}

function runSetIssues(runSet) {
  const all = new Set();
  for (const entry of runSet) {
    for (const issue of entry.issues) all.add(issue);
  }
  return [...all].sort((a, b) => a - b);
}
function findCycles(issues, edges) {
  const adj = adjacency(issues, edges);
  const cycles = stronglyConnected(adj).filter(
    (c) => c.length > 1 || c.some((n) => adj.get(n)?.includes(n) === true),
  );
  for (const cycle of cycles) cycle.sort((a, b) => a - b);
  cycles.sort((a, b) => (a[0] ?? 0) - (b[0] ?? 0));
  return cycles;
}
function transitiveDependents(roots, edges) {
  const next = new Map();
  for (const e of edges) {
    const out = next.get(e.blocker) ?? [];
    out.push(e.dependent);
    next.set(e.blocker, out);
  }
  const seen = new Set(roots);
  const reached = [];
  const walk = (v) => {
    for (const w of next.get(v) ?? []) {
      if (seen.has(w)) continue;
      seen.add(w);
      reached.push(w);
      walk(w);
    }
  };
  for (const r of roots) walk(r);
  return reached.sort((a, b) => a - b);
}
function adjacency(issues, edges) {
  const adj = new Map();
  for (const n of issues) adj.set(n, []);
  for (const e of edges) {
    if (adj.has(e.dependent)) adj.get(e.blocker)?.push(e.dependent);
  }
  return adj;
}
function stronglyConnected(adj) {
  const visited = new Map();
  const stack = [];
  const onStack = new Set();
  const components = [];
  const popComponent = (root) => {
    const component = [];
    for (let w = stack.pop(); w !== undefined; w = w === root ? undefined : stack.pop()) {
      onStack.delete(w);
      component.push(w);
    }
    return component;
  };
  const visit = (v) => {
    const node = { index: visited.size, low: visited.size };
    visited.set(v, node);
    stack.push(v);
    onStack.add(v);
    for (const w of adj.get(v) ?? []) {
      const seen = visited.get(w);
      if (seen === undefined) node.low = Math.min(node.low, visit(w).low);
      else if (onStack.has(w)) node.low = Math.min(node.low, seen.index);
    }
    if (node.low === node.index) components.push(popComponent(v));
    return node;
  };
  for (const v of adj.keys()) if (!visited.has(v)) visit(v);
  return components;
}

