/**
 * The saved workflows' emitted schema module: the zod sources under `ship/src/schemas/`
 * written as JSON Schema literals into {@link SCHEMA_MODULE}, which the workflow sources
 * import and the render inlines. The render can inline no `zod`, so the schemas reach it as data.
 * The module is committed and never hand-edited. {@link checkSchemaModule} is its drift check
 * (`ship/src/build/check-codegen.ts`), and `ship/src/build/emit-workflow-schemas.ts` writes it
 * (`npm run codegen`, before the render).
 *
 * The emitted text is a zero-import TypeScript module: a header comment, then
 * `TOOL_ENVELOPE_SCHEMAS` and `AGENT_OUTPUT_SCHEMAS`, each an `as const` object literal of
 * {@link emitJsonSchema} outputs in the sources' key order. It is formatted by prettier under the
 * repository's config, with LF line endings whatever the checkout's.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

import * as prettier from 'prettier';
import type { z } from 'zod';

import { AGENT_OUTPUTS } from '../schemas/agent-outputs.js';
import { TOOL_ENVELOPES } from '../schemas/tool-envelopes.js';

import { emitJsonSchema } from './json-schema-normalise.js';
import type { RenderCheck } from './workflow-render.js';

/** The emitted module, repository-relative. */
export const SCHEMA_MODULE = 'ship/src/workflow/schemas.generated.ts';

/** Reads the on-disk module by absolute path, or `undefined` when there is none. */
type ModuleReader = (path: string) => string | undefined;

/** The module's header comment. */
const HEADER = [
  '/**',
  ' * Generated by ship/src/build/emit-workflow-schemas.ts from the zod sources under',
  ' * ship/src/schemas/ — do not edit; run `npm run fix`.',
  ' *',
  ' * The JSON Schema each saved-workflow tool call and judgment agent hands',
  ' * the workflow runtime. Render-safe (`ship/src/build/workflow-render.ts`):',
  ' * zero imports, data only.',
  ' */',
].join('\n');

/**
 * The drift check: compare the on-disk module with a fresh emission, line
 * endings normalised. Writes nothing.
 *
 * @returns Resolves to the check: `ok`, or not with a reason. The module
 *   is `missing — never emitted`, or it `differs from the emitted output`.
 */
export async function checkSchemaModule(
  root: string,
  read: ModuleReader = readIfPresent,
): Promise<RenderCheck> {
  const emitted = await renderSchemaModule(root);
  const onDisk = read(resolve(root, SCHEMA_MODULE));

  if (onDisk === undefined) {
    return { target: SCHEMA_MODULE, ok: false, reason: 'missing — never emitted' };
  }

  return onDisk.replaceAll('\r\n', '\n') === emitted
    ? { target: SCHEMA_MODULE, ok: true }
    : { target: SCHEMA_MODULE, ok: false, reason: 'differs from the emitted output' };
}

/**
 * Emit the module and write it LF, replacing any existing file.
 *
 * @returns Resolves to {@link SCHEMA_MODULE}. Rejects as
 *   {@link renderSchemaModule} does, writing nothing.
 */
export async function writeSchemaModule(root: string): Promise<string> {
  const emitted = await renderSchemaModule(root);
  const out = resolve(root, SCHEMA_MODULE);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, emitted, 'utf8');

  return SCHEMA_MODULE;
}

/**
 * The module's text as a fresh emission produces it, LF line endings, with the prettier config
 * {@link SCHEMA_MODULE} resolves under the repository `root`. Rejects when a source schema
 * leaves the construct set ({@link emitJsonSchema}).
 */
async function renderSchemaModule(root: string): Promise<string> {
  const code = [
    HEADER,
    '',
    "/** Each worktree tool's consumed envelope fields. */",
    `export const TOOL_ENVELOPE_SCHEMAS = ${emitAll(TOOL_ENVELOPES)} as const;`,
    '',
    "/** Each judgment agent's output. */",
    `export const AGENT_OUTPUT_SCHEMAS = ${emitAll(AGENT_OUTPUTS)} as const;`,
    '',
  ].join('\n');
  const config = await prettier.resolveConfig(resolve(root, SCHEMA_MODULE));

  return prettier.format(code, { ...config, parser: 'typescript', endOfLine: 'lf' });
}

/**
 * A record of zod schemas as one JSON object literal, each value {@link emitJsonSchema}'s output,
 * in key order.
 */
function emitAll(schemas: Readonly<Record<string, z.ZodType>>): string {
  return JSON.stringify(
    Object.fromEntries(Object.entries(schemas).map(([key, s]) => [key, emitJsonSchema(s)])),
  );
}

/** Read a file by absolute path as UTF-8, or `undefined` when there is no such file. */
function readIfPresent(path: string): string | undefined {
  return existsSync(path) ? readFileSync(path, 'utf8') : undefined;
}
